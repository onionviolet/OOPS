const fs = require('node:fs');
const assert = require('node:assert/strict');
const H = require('../proof_helpers.cjs');
let proof;
(async () => {
    proof = await H.create(process.argv[2], 'boh');
    const title = /^Bench clearance study$/, eda = 'feature_objects.miri';
    const fixture = JSON.parse(fs.readFileSync('/tmp/yairpg-nonfactorio-proof/ready-save.json'));
    for (const [id, n] of [['Sound repair stave', 2], ['Field fitting knife', 1], ['Cyorian research paper', 3], ['Cyorian formula ink', 3]]) H.put(fixture, id, n);
    let {page, context} = await proof.open(fixture);
    let card = await proof.here(page, title);
    const click = name => proof.card(page, title).getByRole('button', {name}).click();
    await click(/Ask Eda about the bench clearance manual/);
    await click(/Commission a clearance manual/);
    const pending = await proof.save(page);
    assert.equal(H.count(pending, 'Cyorian research paper'), 2);
    assert.equal(H.count(pending, 'Bench clearance manual'), 0);
    assert.equal(pending.character.money, fixture.character.money - 2);
    await click(/Cancel work/);
    const cancelled = await proof.save(page);
    assert.equal(cancelled.character.money, fixture.character.money);
    assert.equal(H.count(cancelled, 'Cyorian research paper'), 3);
    assert.equal(H.count(cancelled, 'Cyorian formula ink'), 3);
    assert.equal(cancelled.expansion.actors[eda].resources.coins, fixture.expansion.actors[eda].resources.coins);
    proof.record('Cancelling a commissioned copy returns its paper, ink and fee, with no manual or Eda wage.');
    await click(/Commission a clearance manual/);
    const heldCopy = await proof.save(page);
    fs.writeFileSync(`${proof.output}/pending-copy.json`, JSON.stringify(heldCopy, null, 2));
    await proof.reload(page); await proof.here(page, title);
    await proof.waitDone(page, 'steam.boh.copy_manual');
    let copied = await proof.save(page);
    assert.equal(H.count(copied, 'Bench clearance manual'), 1);
    assert.equal(copied.expansion.actors[eda].resources.coins, fixture.expansion.actors[eda].resources.coins + 2);
    proof.record('Saved pending copy reloads and produces one actual manual, consuming paper/ink and paying Eda once.');
    await click(/Try the difficult reading/); await proof.waitDone(page, 'steam.boh.trial');
    const failed = await proof.save(page);
    assert.equal(failed.expansion.actors.player.facts['steam.boh.diagnosticAvailable'], true);
    assert.equal(failed.expansion.actors.player.facts['steam.boh.procedureVersion'], undefined);
    assert.equal(H.count(failed, 'Bench clearance manual'), 1);
    assert.equal(H.count(failed, 'Sound repair stave'), 2);
    proof.record('The disclosed difficult reading returns manual/sample and leaves a specific missing comparison, without learning the procedure.');
    const rest = proof.card(page, title).getByRole('button', {name: /Rest from clearance study/});
    if (await rest.count()) {await rest.click(); await proof.waitDone(page, 'steam.boh.rest'); proof.record('Two-minute study rest clears its fatigue before the comparison.');}
    const compare = proof.card(page, title).getByRole('button', {name: /Resolve the missing clearance comparison/});
    await page.waitForFunction(() => {
        const b = Array.from(document.querySelectorAll('#feature_expansion_panel button')).find(b => b.textContent.includes('Resolve the missing clearance comparison'));
        return b && b.getAttribute('aria-disabled') !== 'true' && !b.disabled;
    }, null, {timeout: 180000});
    await compare.click(); await proof.waitDone(page, 'steam.boh.compare');
    await click(/Read the prepared manual/); await proof.waitDone(page, 'steam.boh.read');
    const learned = await proof.save(page);
    assert.equal(learned.expansion.actors.player.facts['steam.boh.preparationVersion'], 1);
    assert.equal(learned.expansion.actors.player.facts['steam.boh.diagnosticAvailable'], false);
    assert.equal(learned.expansion.actors.player.facts['steam.boh.procedureVersion'], 1);
    assert.equal(learned.expansion.simulation.knowledge.player['steam.boh.procedure'].stage, 'understood');
    assert.ok(learned.expansion.simulation.knowledge.player['steam.boh.diagnostic']);
    proof.record('Recovery, exact comparison and prepared reading turn the failure into retained understanding, preserving its earlier history.');
    await click(/Make 2 survey kits with your sharp field fitting knife/);
    const heldKit = await proof.save(page);
    assert.equal(H.count(heldKit, 'Bench clearance manual'), 0);
    assert.equal(H.count(heldKit, 'Field fitting knife'), 0);
    await click(/Cancel work/);
    const kitCancelled = await proof.save(page);
    assert.equal(H.count(kitCancelled, 'Bench clearance manual'), 1);
    assert.equal(H.count(kitCancelled, 'Field fitting knife'), 1);
    assert.equal(H.count(kitCancelled, 'Sound repair stave'), 2);
    assert.equal(H.count(kitCancelled, 'Prepared survey kit'), 0);
    proof.record('Cancelling kit work returns the held manual, unchanged sharp knife and actual materials.');
    await click(/Make 2 survey kits with your sharp field fitting knife/); await proof.waitDone(page, 'steam.boh.kits_sharp');
    const kits = await proof.save(page);
    assert.equal(H.count(kits, 'Prepared survey kit'), 2);
    assert.equal(H.count(kits, 'Bench clearance manual'), 1);
    assert.equal(H.count(kits, 'Dulled field fitting knife'), 1);
    assert.equal(H.count(kits, 'Sound repair stave'), 0);
    fs.writeFileSync(`${proof.output}/learned-kits.json`, JSON.stringify(kits, null, 2));
    await page.screenshot({path: `${proof.output}/learned-kits.png`, fullPage: true});
    proof.record('The learned method makes two actual native survey kits, returns the manual and dulls the same knife.');
    const fitting = await proof.here(page, /^Fitting tools & materials$/);
    await fitting.getByRole('button', {name: /Deliver two real survey kits to Eda/}).click();
    await proof.waitDone(page, 'feature_objects.deliver_kits');
    assert.equal(H.count(await proof.save(page), 'Prepared survey kit'), 0);
    await proof.importSave(page, kits); await proof.here(page, title);
    const imported = await proof.save(page);
    assert.equal(H.count(imported, 'Prepared survey kit'), 2);
    assert.equal(H.count(imported, 'Bench clearance manual'), 1);
    assert.equal(imported.expansion.actors.player.facts['steam.boh.procedureVersion'], 1);
    proof.record('Native file import restores the learned procedure, physical manual and kits after an actual kit-order delivery spent them.');
    await context.close();
    // Alternate route uses the real acquired manual but no failed-trial records.
    ({page, context} = await proof.open(copied)); await proof.here(page, title);
    await click(/Ask Eda to guide the comparison/); await proof.waitDone(page, 'steam.boh.guided');
    const guided = await proof.save(page);
    assert.equal(guided.character.money, copied.character.money - 3);
    assert.equal(guided.expansion.actors.player.facts['steam.boh.preparationVersion'], 1);
    assert.equal(guided.expansion.actors.player.facts['steam.boh.diagnosticAvailable'], undefined);
    assert.equal(guided.expansion.actors.player.facts['steam.boh.procedureVersion'], undefined);
    proof.record('Paid guidance supplies preparation without the failed-reading diagnostic or learned procedure.');
    assert.deepEqual(proof.errors, []);
    await proof.finish(['Generated funded fixtures prove these local paths, not natural paper/ink acquisition or director balance acceptance.', 'Fine-knife, copy-after-loss, support loss and fatigue expiry have bounded reducer checks; broader browser branches remain open.']);
})().catch(async error => {if (proof) await proof.fail(error); console.error(error); process.exit(1);});
