const fs = require('node:fs');
const assert = require('node:assert/strict');
const H = require('../proof_helpers.cjs');
let proof;
(async () => {
    proof = await H.create(process.argv[2], 'boh-followthrough');
    const learned = JSON.parse(fs.readFileSync('/tmp/yairpg-nonfactorio-proof/boh/learned-kits.json'));
    const pending = JSON.parse(fs.readFileSync('/tmp/yairpg-nonfactorio-proof/boh/pending-copy.json'));
    const lost = structuredClone(learned); delete lost.inventories.person.main_character[H.key('Bench clearance manual')];
    const title = /^Bench clearance study$/;
    const {page} = await proof.open(lost); await proof.here(page, title);
    const click = name => proof.card(page, title).getByRole('button', {name}).click();
    const before = await proof.save(page);
    assert.equal(before.expansion.actors.player.facts['steam.boh.procedureVersion'], 1);
    assert.equal(H.count(before, 'Bench clearance manual'), 0);
    await click(/Commission a clearance manual/); await proof.waitDone(page, 'steam.boh.copy_manual', 1);
    const replacement = await proof.save(page);
    assert.equal(H.count(replacement, 'Bench clearance manual'), 1);
    assert.equal(replacement.character.money, before.character.money - 2);
    assert.equal(H.count(replacement, 'Cyorian research paper'), H.count(before, 'Cyorian research paper') - 1);
    assert.equal(replacement.expansion.actors.player.facts['steam.boh.procedureVersion'], 1);
    proof.record('A generated lost-copy state keeps the learned procedure; another real paid copy consumes paper/ink/fee and restores one manual.');
    await proof.importSave(page, pending); await proof.here(page, title);
    await proof.waitDone(page, 'steam.boh.copy_manual');
    const restored = await proof.save(page);
    assert.equal(H.count(restored, 'Bench clearance manual'), 1);
    assert.equal(restored.expansion.actors.player.completed['steam.boh.copy_manual'], 1);
    assert.equal(restored.expansion.actors.player.facts['steam.boh.procedureVersion'], undefined);
    assert.equal(restored.character.money, pending.character.money);
    proof.record('Native file import restores the actual earlier pending copy and completes it once, restoring its earlier unlearned history.');
    await page.screenshot({path: `${proof.output}/replacement-and-import.png`, fullPage: true});
    assert.deepEqual(proof.errors, []);
    await proof.finish(['Copy removal was an explicit generated fixture, not a tested trading route.', 'Resource failures are recorded separately by URL; no application exception is hidden.']);
})().catch(async error => {if (proof) await proof.fail(error); console.error(error); process.exit(1);});
