const fs = require('node:fs');
const assert = require('node:assert/strict');
const H = require('../proof_helpers.cjs');
let proof;
(async () => {
    proof = await H.create(process.argv[2], 'lamb');
    const ready = JSON.parse(fs.readFileSync('/tmp/yairpg-nonfactorio-proof/ready-save.json'));
    const eda = 'feature_objects.miri', method = 'feature_objects.grain_matching', title = /^Eda’s fitting agreement$/;
    const {page} = await proof.open(ready);
    const fitting = await proof.here(page, /^Fitting tools & materials$/);
    assert.equal((await proof.save(page)).expansion.actors[eda].facts['steam.lamb.office'], undefined);
    await fitting.getByRole('button', {name: /Watch Eda cut her actual grain sample/}).click();
    await proof.waitDone(page, 'feature_objects.observe_alignment');
    await fitting.getByRole('button', {name: /Practice Grain matching with Eda/}).click();
    await proof.waitDone(page, 'feature_objects.learn');
    const qualified = await proof.save(page);
    assert.equal(qualified.expansion.actors[eda].facts['steam.lamb.office'], undefined);
    assert.ok(qualified.expansion.simulation.knowledge[eda]['feature_objects.demonstration']);
    proof.record('Actual Eda demonstration and supervised native practice earn the prerequisites without automatically appointing her.');
    await fitting.getByRole('button', {name: /Buy Eda's demonstrated matched stave/}).click();
    assert.equal(H.count(await proof.save(page), 'Matched repair stave'), 1);
    await proof.here(page, title);
    const click = name => proof.card(page, title).getByRole('button', {name}).click();
    await click(/Agree Eda’s fitting assessor appointment/); await proof.waitDone(page, 'steam.lamb.appoint');
    const appointed = await proof.save(page);
    assert.equal(appointed.expansion.actors[eda].facts['steam.lamb.office'], true);
    assert.equal(appointed.expansion.actors.player.facts['steam.lamb.office'], undefined);
    const retainedSource = structuredClone(appointed.expansion.actors[eda].sources[method]);
    proof.record('One willing minute appoints the same Eda; the office belongs to her and grants no replacement source.');
    await click(/inspect a matched stave with her dulled fine guide/);
    const held = await proof.save(page);
    assert.equal(H.count(held, 'Matched repair stave'), 0);
    assert.equal(held.expansion.simulation.owners[eda][H.key('Dulled fine field fitting knife')] || 0, 0);
    assert.equal(held.character.money, appointed.character.money - 1);
    fs.writeFileSync(`${proof.output}/pending-inspection.json`, JSON.stringify(held, null, 2));
    await click(/Cancel work/);
    const cancelled = await proof.save(page);
    assert.equal(cancelled.character.money, appointed.character.money);
    assert.equal(H.count(cancelled, 'Matched repair stave'), 1);
    assert.equal(cancelled.expansion.simulation.owners[eda][H.key('Dulled fine field fitting knife')], 1);
    assert.equal(cancelled.expansion.actors.player.facts['steam.lamb.approval'], undefined);
    assert.equal(cancelled.expansion.actors[eda].resources.coins, appointed.expansion.actors[eda].resources.coins);
    proof.record('Inspection really holds the owned part and Eda guide; cancellation restores fee, unchanged items and no approval or wage.');
    await click(/inspect a matched stave with her dulled fine guide/);
    await proof.reload(page); await proof.here(page, title); await proof.waitDone(page, 'steam.lamb.inspect_fineDull');
    const approved = await proof.save(page);
    assert.equal(approved.expansion.actors.player.facts['steam.lamb.approval'], true);
    assert.equal(H.count(approved, 'Matched repair stave'), 1);
    assert.equal(approved.expansion.simulation.owners[eda][H.key('Dulled fine field fitting knife')], 1);
    assert.equal(approved.expansion.actors[eda].resources.coins, appointed.expansion.actors[eda].resources.coins + 1);
    fs.writeFileSync(`${proof.output}/approved.json`, JSON.stringify(approved, null, 2));
    proof.record('Saved held inspection reloads, returns the same counted part and guide, pays Eda once and issues the one class approval.');
    await click(/Deliver one approved matched stave/); await proof.waitDone(page, 'steam.lamb.deliver');
    const delivered = await proof.save(page);
    assert.equal(H.count(delivered, 'Matched repair stave'), 0);
    assert.equal(delivered.expansion.simulation.owners[eda][H.key('Matched repair stave')], 1);
    assert.equal(delivered.character.money, approved.character.money + 3);
    assert.equal(delivered.expansion.actors[eda].resources.coins, approved.expansion.actors[eda].resources.coins - 3);
    assert.equal(delivered.expansion.actors.player.facts['steam.lamb.approval'], false);
    assert.equal(delivered.expansion.actors.player.completed['steam.lamb.deliver'], 1);
    assert.equal(await proof.card(page, title).getByRole('button', {name: /Deliver one approved matched stave/}).count(), 0);
    proof.record('One finite order transfers the actual native stave to Eda, spends three of her coins and consumes its approval without replay.');
    await proof.importSave(page, approved); await proof.here(page, title);
    const imported = await proof.save(page);
    assert.equal(imported.character.money, approved.character.money);
    assert.equal(imported.expansion.actors.player.facts['steam.lamb.approval'], true);
    assert.equal(H.count(imported, 'Matched repair stave'), 1);
    assert.equal(imported.expansion.actors.player.completed['steam.lamb.deliver'], undefined);
    proof.record('Native file import restores the actual earlier approved-but-unsettled order, including part, purse and history.');
    await click(/Deliver one approved matched stave/); await proof.waitDone(page, 'steam.lamb.deliver');
    await click(/End the fitting assessor agreement/);
    const ended = await proof.save(page);
    assert.equal(ended.expansion.actors[eda].facts['steam.lamb.office'], false);
    assert.deepEqual(ended.expansion.actors[eda].sources[method], retainedSource);
    assert.ok(ended.expansion.simulation.knowledge.player['steam.lamb.appointment']);
    assert.ok(ended.expansion.simulation.knowledge.player['steam.lamb.delivery']);
    assert.equal(ended.expansion.actors.player.completed['steam.lamb.end'], 1);
    assert.equal(await proof.card(page, title).getByRole('button', {name: /inspect a matched stave/}).count(), 0);
    fs.writeFileSync(`${proof.output}/ended.json`, JSON.stringify(ended, null, 2));
    await proof.reload(page); await proof.here(page, title);
    assert.equal((await proof.save(page)).expansion.actors[eda].facts['steam.lamb.office'], false);
    await page.screenshot({path: `${proof.output}/ended-agreement.png`, fullPage: true});
    proof.record('Ending removes future service while preserving Eda’s trained method and completed work; reload retains that distinction.');
    assert.deepEqual(proof.errors, []);
    await proof.finish(['Generated funded Eda fixture; actual demonstration/practice and all described transactions were played, but natural opening/pacing are not proved.', 'Sharp-guide route, delivery refund, source-loss ending and in-flight support loss have bounded checks; separate browser branches remain open. Approval is a fungible item-class receipt, not per-copy identity.']);
})().catch(async error => {if (proof) await proof.fail(error); console.error(error); process.exit(1);});
