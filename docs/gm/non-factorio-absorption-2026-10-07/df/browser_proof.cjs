const fs = require('node:fs');
const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
const {chromium} = require('/tmp/yairpg-nonfactorio-proof-tools/node_modules/playwright');
const url = process.argv[2];
const output = '/tmp/yairpg-nonfactorio-proof/df';
fs.mkdirSync(output, {recursive: true});
const ready = JSON.parse(fs.readFileSync('/tmp/yairpg-nonfactorio-proof/ready-save.json'));
const eda = 'feature_objects.miri', stave = '{"id":"Sound repair stave"}';
const errors = [], findings = [];
const record = text => {findings.push(text); fs.writeFileSync(output + '/progress.json', JSON.stringify({url, errors, findings}, null, 2)); console.log(text);};
let proofBrowser;
(async () => {
    const {encodeSaveFile} = await import(pathToFileURL(process.cwd() + '/src/save_files.js'));
    const browser = proofBrowser = await chromium.launch({headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
        args: ['--disable-gpu', '--use-angle=swiftshader', '--yairpg-test-lane=nonfactorio']});
    const save = async page => {await page.evaluate(() => window.saveProgress()); return page.evaluate(() => JSON.parse(localStorage.getItem('save data')));};
    const open = async fixture => {
        const context = await browser.newContext({viewport: {width: 1500, height: 1000}});
        await context.addInitScript(data => {if (!localStorage.getItem('save data')) localStorage.setItem('save data', JSON.stringify(data));}, fixture);
        const page = await context.newPage(); page.setDefaultTimeout(90000); page.setDefaultNavigationTimeout(120000);
        page.on('pageerror', e => errors.push(e.message));
        console.log('Opening generated fixture'); await page.goto(url, {waitUntil: 'domcontentloaded'}); await page.getByText('PLAY', {exact: true}).click();
        if (await page.getByText('Confirm', {exact: true}).isVisible()) await page.getByText('Confirm', {exact: true}).click();
        await here(page);
        return {page, context};
    };
    const here = async page => {
        if (!await page.locator('#notebook_box_div').isVisible()) await page.locator('#journal_show_notebook').click();
        await page.locator('[data-notebook-view="here"]').click();
        const panel = page.locator('#feature_expansion_panel');
        if (!await panel.evaluate(n => n.open)) await panel.locator(':scope > summary').click();
        const summary = panel.locator('summary').filter({hasText: /^Eda’s offered-stock reports$/});
        await summary.waitFor();
        if (!await summary.locator('..').evaluate(n => n.open)) await summary.click();
    };
    const card = page => page.locator('#feature_expansion_panel details').filter({has: page.locator('summary').filter({hasText: /^Eda’s offered-stock reports$/})});
    const click = (page, name) => card(page).getByRole('button', {name}).click();
    const waitDone = (page, id) => page.waitForFunction(id => JSON.parse(localStorage.getItem('save data')).expansion.actors.player.completed[id] > 0, id, {timeout: 120000});
    let {page, context} = await open(ready);
    await click(page, /Ask Eda about her offered-stock reports/);
    await click(page, /Pay Eda for a full stock count/);
    const pending = await save(page);
    assert.equal(pending.character.money, ready.character.money - 2);
    const job = pending.expansion.simulation.jobs.find(j => j.commandId === 'steam.df.count');
    assert.ok(job, 'A three-minute report must be saved while pending.');
    assert.equal(job.steamDFSample.amount, 2);
    fs.writeFileSync(output + '/pending.json', JSON.stringify(pending, null, 2));
    console.log('Saved pending count, reloading'); await page.reload({waitUntil: 'domcontentloaded'}); await page.getByText('PLAY', {exact: true}).click(); await here(page);
    await waitDone(page, 'steam.df.count');
    let counted = await save(page);
    const receipt = JSON.parse(counted.expansion.actors.player.facts['steam.df.report']);
    assert.equal(receipt.amount, 2); assert.equal(receipt.sampledCause, job.id);
    assert.equal(counted.expansion.actors[eda].resources.coins, ready.expansion.actors[eda].resources.coins + 2);
    await click(page, /Buy the currently reported pair/);
    const bought = await save(page);
    fs.writeFileSync(output + '/bought.json', JSON.stringify(bought, null, 2));
    assert.equal(bought.character.money, ready.character.money - 6);
    assert.equal(bought.inventories.person.main_character[stave].count, 2);
    assert.equal(bought.expansion.simulation.owners[eda][stave] || 0, 0);
    assert.ok((await card(page).innerText()).includes('old count is out of date'));
    assert.equal(await card(page).getByRole('button', {name: /reported pair/}).getAttribute('aria-disabled'), 'true');
    record('Saved pending full-count reservation reloads, issues the same sample/cause, pays Eda once, then four native coins transfer two real staves and invalidate the old report.');
    await page.screenshot({path: output + '/received-pair.png', fullPage: true});
    const fittings = page.locator('#feature_expansion_panel details').filter({has: page.locator('summary').filter({hasText: /^Fitting tools & materials$/})});
    if (!await fittings.evaluate(n => n.open)) await fittings.locator(':scope > summary').click();
    await fittings.getByRole('button', {name: /Buy one actual sharp fitting knife/}).click();
    assert.equal((await save(page)).character.money, bought.character.money - 6);
    // Native import reads an actual newly generated encoded envelope, not user data.
    const encoded = encodeSaveFile(JSON.stringify(bought));
    const importedLoad = page.waitForEvent('domcontentloaded', {timeout: 120000});
    await page.locator('#saved_file_input').setInputFiles({name: 'generated-df-save.txt', mimeType: 'text/plain', buffer: Buffer.from(encoded)});
    await importedLoad; await page.getByText('PLAY', {exact: true}).click(); await here(page);
    const imported = await save(page);
    assert.equal(imported.character.money, bought.character.money);
    assert.equal(imported.inventories.person.main_character[stave].count, 2);
    assert.equal(imported.expansion.actors.player.facts['steam.df.report'], bought.expansion.actors.player.facts['steam.df.report']);
    assert.equal(imported.inventories.person.main_character['{"id":"Field fitting knife"}'], undefined);
    record('Native generated-file import retains native stock, money, dated report and stale witness.');
    const afterImportFittings = page.locator('#feature_expansion_panel details').filter({has: page.locator('summary').filter({hasText: /^Fitting tools & materials$/})});
    await afterImportFittings.locator(':scope > summary').click();
    await afterImportFittings.getByRole('button', {name: /Buy one actual sharp fitting knife/}).click();
    await afterImportFittings.getByRole('button', {name: /Cut two sound staves into two usable survey kits/}).click();
    await waitDone(page, 'feature_objects.kit_sharp_own');
    const kits = await save(page);
    assert.equal(kits.inventories.person.main_character[stave], undefined);
    assert.equal(kits.inventories.person.main_character['{"id":"Prepared survey kit"}'].count, 2);
    record('The actually received pair feeds the existing sharp-knife native batch and becomes two real Prepared survey kits.');
    const beforeDelivery = kits.character.money;
    await afterImportFittings.getByRole('button', {name: /Deliver two real survey kits to Eda/}).click();
    await waitDone(page, 'feature_objects.deliver_kits');
    const delivered = await save(page);
    assert.equal(delivered.inventories.person.main_character['{\"id\":\"Prepared survey kit\"}'], undefined);
    assert.equal(delivered.character.money, beforeDelivery + 2);
    assert.equal(delivered.expansion.simulation.owners[eda]['{\"id\":\"Prepared survey kit\"}'], 2);
    record('The two kits satisfy Eda’s existing finite order, leave native inventory and pay two coins from her purse.');
    await context.close();
    ({page, context} = await open(ready));
    await click(page, /Ask Eda about her offered-stock reports/);
    await click(page, /Pay Eda for a full stock count/);
    await click(page, /Cancel work/);
    const cancelled = await save(page);
    assert.equal(cancelled.character.money, ready.character.money);
    assert.equal(cancelled.expansion.actors.player.facts['steam.df.report'], undefined);
    assert.equal(cancelled.expansion.actors[eda].resources.coins, ready.expansion.actors[eda].resources.coins);
    record('Cancelling the actual pending report returns its reserved fee and publishes neither report nor Eda wage.');
    await click(page, /Pay Eda for a stock estimate/); await waitDone(page, 'steam.df.estimate');
    const estimated = await save(page), estimate = JSON.parse(estimated.expansion.actors.player.facts['steam.df.report']);
    assert.equal(estimate.precision, 'estimate'); assert.equal(estimate.amount, undefined);
    assert.equal(estimate.lower, 0); assert.equal(estimate.upper, 2);
    assert.equal(await card(page).getByRole('button', {name: /reported pair/}).getAttribute('aria-disabled'), 'true');
    record('Paid estimate exposes only its bracket and cannot authorize the two-stave purchase.');
    await click(page, /Pay Eda for a full stock count/); await waitDone(page, 'steam.df.count');
    const oldPurchaseFittings = page.locator('#feature_expansion_panel details').filter({has: page.locator('summary').filter({hasText: /^Fitting tools & materials$/})});
    await oldPurchaseFittings.locator(':scope > summary').click();
    await oldPurchaseFittings.getByRole('button', {name: /Buy Eda's one actual sound stave/}).click();
    const changed = await save(page);
    assert.equal(changed.expansion.simulation.owners[eda][stave], 1);
    assert.ok((await card(page).innerText()).includes('old count is out of date'));
    assert.equal(await card(page).getByRole('button', {name: /reported pair/}).getAttribute('aria-disabled'), 'true');
    record('Existing single-stave purchase changes the shared mutation witness and makes the earlier full count stale.');
    assert.deepEqual(errors, []);
    fs.writeFileSync(output + '/result.json', JSON.stringify({url, errors, findings,
        limits: ['Uses the generated funded Eda fixture; natural rat-field progression and director balance acceptance are not proved.',
            'Lost-support refund is covered by bounded leaf checks; separate browser support-loss and malformed import branches remain open.']}, null, 2));
    await browser.close(); console.log(JSON.stringify({findings, errors}));
})().catch(async error => {if (proofBrowser) await proofBrowser.close().catch(() => {});fs.writeFileSync(output + '/failure.txt', error.stack); console.error(error); process.exit(1);});
