const fs = require('node:fs');
const assert = require('node:assert/strict');
const H = require('../proof_helpers.cjs');
let proof;
(async () => {
    proof = await H.create(process.argv[2], 'df-followthrough');
    const ready = JSON.parse(fs.readFileSync('/tmp/yairpg-nonfactorio-proof/ready-save.json'));
    const pending = JSON.parse(fs.readFileSync('/tmp/yairpg-nonfactorio-proof/df/pending.json'));
    const job = pending.expansion.simulation.jobs.find(j => j.commandId === 'steam.df.count');
    const eda = 'feature_objects.miri', title = /^Eda’s offered-stock reports$/;
    let {page, context} = await proof.open(pending); await proof.here(page, title);
    const click = name => proof.card(page, title).getByRole('button', {name}).click();
    await proof.waitDone(page, 'steam.df.count');
    const counted = await proof.save(page);
    const receipt = JSON.parse(counted.expansion.actors.player.facts['steam.df.report']);
    assert.equal(receipt.sampledCause, job.id); assert.equal(receipt.amount, 2);
    assert.equal(counted.expansion.actors[eda].resources.coins, ready.expansion.actors[eda].resources.coins + 2);
    await click(/Buy the currently reported pair/);
    const bought = await proof.save(page);
    assert.equal(H.count(bought, 'Sound repair stave'), 2);
    assert.equal(bought.expansion.simulation.owners[eda][H.key('Sound repair stave')] || 0, 0);
    assert.equal(bought.character.money, ready.character.money - 6);
    assert.ok((await proof.card(page, title).innerText()).includes('old count is out of date'));
    assert.equal(await proof.card(page, title).getByRole('button', {name: /reported pair/}).getAttribute('aria-disabled'), 'true');
    proof.record('The preserved pending count loads, issues its original sample/cause and wage once; four coins then transfer two staves and invalidate the old count.');
    fs.writeFileSync(`${proof.output}/bought.json`, JSON.stringify(bought, null, 2));
    let fitting = await proof.here(page, /^Fitting tools & materials$/);
    await fitting.getByRole('button', {name: /Buy one actual sharp fitting knife/}).click();
    assert.equal((await proof.save(page)).character.money, bought.character.money - 6);
    await proof.importSave(page, bought); await proof.here(page, title);
    const imported = await proof.save(page);
    assert.equal(imported.character.money, bought.character.money);
    assert.equal(H.count(imported, 'Field fitting knife'), 0);
    assert.equal(H.count(imported, 'Sound repair stave'), 2);
    assert.equal(imported.expansion.actors.player.facts['steam.df.report'], bought.expansion.actors.player.facts['steam.df.report']);
    proof.record('Native generated-file import restores prior money, staves and dated report after a real knife purchase changed them.');
    fitting = await proof.here(page, /^Fitting tools & materials$/);
    await fitting.getByRole('button', {name: /Buy one actual sharp fitting knife/}).click();
    await fitting.getByRole('button', {name: /Cut two sound staves into two usable survey kits/, exact: false}).first().click();
    await proof.waitDone(page, 'feature_objects.kit_sharp_own');
    const kits = await proof.save(page);
    assert.equal(H.count(kits, 'Sound repair stave'), 0); assert.equal(H.count(kits, 'Prepared survey kit'), 2);
    await fitting.getByRole('button', {name: /Deliver two real survey kits to Eda/}).click();
    await proof.waitDone(page, 'feature_objects.deliver_kits');
    const delivered = await proof.save(page);
    assert.equal(H.count(delivered, 'Prepared survey kit'), 0);
    assert.equal(delivered.character.money, kits.character.money + 2);
    assert.equal(delivered.expansion.simulation.owners[eda][H.key('Prepared survey kit')], 2);
    proof.record('The purchased pair becomes two native kits and satisfies Eda’s existing paid kit order.');
    await page.screenshot({path: `${proof.output}/kit-order.png`, fullPage: true});
    await context.close();
    ({page, context} = await proof.open(ready)); await proof.here(page, title);
    await click(/Ask Eda about her offered-stock reports/); await click(/Pay Eda for a full stock count/); await click(/Cancel work/);
    const cancelled = await proof.save(page);
    assert.equal(cancelled.character.money, ready.character.money);
    assert.equal(cancelled.expansion.actors.player.facts['steam.df.report'], undefined);
    assert.equal(cancelled.expansion.actors[eda].resources.coins, ready.expansion.actors[eda].resources.coins);
    proof.record('Cancelling the actual count returns its fee without a report or Eda wage.');
    await click(/Pay Eda for a stock estimate/); await proof.waitDone(page, 'steam.df.estimate');
    const estimate = JSON.parse((await proof.save(page)).expansion.actors.player.facts['steam.df.report']);
    assert.equal(estimate.amount, undefined); assert.equal(estimate.lower, 0); assert.equal(estimate.upper, 2);
    assert.equal(await proof.card(page, title).getByRole('button', {name: /reported pair/}).getAttribute('aria-disabled'), 'true');
    proof.record('The paid estimate discloses its bracket and cannot authorize a pair.');
    await click(/Pay Eda for a full stock count/); await proof.waitDone(page, 'steam.df.count');
    fitting = await proof.here(page, /^Fitting tools & materials$/);
    await fitting.getByRole('button', {name: /Buy Eda's one actual sound stave/}).click();
    assert.equal((await proof.save(page)).expansion.simulation.owners[eda][H.key('Sound repair stave')], 1);
    assert.equal(await proof.card(page, title).getByRole('button', {name: /reported pair/}).getAttribute('aria-disabled'), 'true');
    proof.record('The existing single-stave purchase invalidates the same exact-count witness.');
    assert.deepEqual(proof.errors, []);
    await proof.finish(['Generated funded workshop fixture, not natural opening progression or director balance acceptance.', 'Separate support-loss and malformed-import browser branches remain open; bounded validators cover their model rules.']);
})().catch(async error => {if (proof) await proof.fail(error); console.error(error); process.exit(1);});
