const fs = require('node:fs');
const assert = require('node:assert/strict');
const H = require('../proof_helpers.cjs');
let proof;
(async () => {
    proof = await H.create(process.argv[2], 'oni');
    const title = /^Your sheltered nursery$/;
    const fixture = JSON.parse(fs.readFileSync('/tmp/yairpg-nonfactorio-proof/pre-eda-save.json'));
    fixture['current location'] = 'Shack'; fixture.global_flags.is_crafting_unlocked = true;
    fixture.levels.person.main_character.skill_xp.Cooking = 1000000; fixture.availabilities.skill.Cooking |= 1;
    H.put(fixture, 'Cooking herbs', 1); H.put(fixture, 'Goat meat', 2);
    const {page} = await proof.open(fixture); await proof.here(page, title);
    const click = name => proof.card(page, title).getByRole('button', {name}).click();
    assert.equal((await proof.save(page)).expansion.simulation, null);
    await click(/Consider a sheltered nursery/);
    const opened = await proof.save(page);
    assert.equal(opened.expansion.simulation.people['feature_objects.miri'], undefined);
    assert.equal(opened.expansion.simulation.sites['steam.oni.nursery_tray'], undefined);
    proof.record('At the generated unlocked Shack, the explicit plan enrolls ordinary services without Eda and creates no tray or herbs.');
    await click(/Build your sheltered nursery tray/);
    const reserved = await proof.save(page);
    assert.equal(H.count(reserved, 'Rough wood log'), H.count(fixture, 'Rough wood log') - 2);
    assert.equal(reserved.character.money, fixture.character.money - 2);
    assert.equal(reserved.expansion.simulation.sites['steam.oni.nursery_tray'], undefined);
    await click(/Cancel work/);
    const cancelledBuild = await proof.save(page);
    assert.equal(cancelledBuild.character.money, fixture.character.money);
    assert.equal(H.count(cancelledBuild, 'Rough wood log'), H.count(fixture, 'Rough wood log'));
    assert.equal(cancelledBuild.expansion.simulation.sites['steam.oni.nursery_tray'], undefined);
    proof.record('Construction holds actual wood and money; cancellation returns them and creates no site.');
    await click(/Build your sheltered nursery tray/);
    fs.writeFileSync(`${proof.output}/pending-build.json`, JSON.stringify(await proof.save(page), null, 2));
    await proof.reload(page); await proof.here(page, title); await proof.waitDone(page, 'steam.oni.build_tray');
    const built = await proof.save(page);
    assert.equal(built.expansion.simulation.sites['steam.oni.nursery_tray'].owner, 'player');
    assert.equal(built.expansion.actors.player.facts['steam.oni.trayBuilt'], true);
    assert.equal(H.count(built, 'Cooking herbs'), 1);
    proof.record('Pending construction reloads and creates exactly the owned tray, with no automatic crop or herb gift.');
    await click(/Tend a fresh nursery round/);
    const held = await proof.save(page);
    assert.equal(H.count(held, 'Cooking herbs'), 0); assert.equal(H.count(held, 'Tree sap'), H.count(fixture, 'Tree sap') - 1);
    await click(/Cancel work/);
    const cancelled = await proof.save(page);
    assert.equal(H.count(cancelled, 'Cooking herbs'), 1); assert.equal(H.count(cancelled, 'Tree sap'), H.count(fixture, 'Tree sap'));
    assert.equal(cancelled.expansion.actors.player.completed['steam.oni.tend_cycle'], undefined);
    proof.record('Cancelling tending returns both joint inputs and leaves the existing empty tray, without a harvest.');
    await click(/Tend a fresh nursery round/);
    const pending = await proof.save(page);
    fs.writeFileSync(`${proof.output}/pending-cycle.json`, JSON.stringify(pending, null, 2));
    await proof.waitDone(page, 'steam.oni.tend_cycle');
    const first = await proof.save(page);
    assert.equal(H.count(first, 'Cooking herbs'), 2); assert.equal(H.count(first, 'Tree sap'), H.count(fixture, 'Tree sap') - 1);
    await click(/Tend a fresh nursery round/); await proof.waitDone(page, 'steam.oni.tend_cycle', 1);
    const twice = await proof.save(page);
    assert.equal(H.count(twice, 'Cooking herbs'), 3); assert.equal(H.count(twice, 'Tree sap'), H.count(fixture, 'Tree sap') - 2);
    assert.equal(twice.expansion.actors.player.completed['steam.oni.tend_cycle'], 2);
    proof.record('Two separately chosen rounds each spend new herbs and sap; one initial bundle becomes three actual carried bundles.');
    await page.getByText('Move somewhere else', {exact: false}).click();
    await page.locator('[data-travel="Village"]').first().click();
    await proof.here(page, title);
    assert.equal(await proof.card(page, title).getByRole('button', {name: /Tend a fresh nursery round/}).getAttribute('aria-disabled'), 'true');
    proof.record('Ordinary travel to the Village leaves the tray intact but blocks tending outside its supported shelter.');
    await page.locator('.choice_craft').click();
    await page.locator('.crafting_mainpage_button[data-crafting_category="cooking"]').click();
    await page.locator('[data-crafting_category="cooking"][data-crafting_subcategory="items"] [data-recipe_id="Goat stew"] .recipe_item_name').click();
    const cooked = await proof.save(page);
    assert.equal(H.count(cooked, 'Cooking herbs'), 1); assert.equal(H.count(cooked, 'Goat meat'), 0); assert.equal(H.count(cooked, 'Goat stew'), 1);
    proof.record('The existing native Goat stew recipe consumes two produced herb bundles and real meat into a carried meal.');
    await page.screenshot({path: `${proof.output}/cooked-harvest.png`, fullPage: true});
    await proof.importSave(page, pending); await proof.here(page, title); await proof.waitDone(page, 'steam.oni.tend_cycle');
    const imported = await proof.save(page);
    assert.equal(imported['current location'], 'Shack');
    assert.equal(H.count(imported, 'Cooking herbs'), 2);
    assert.equal(imported.expansion.actors.player.completed['steam.oni.tend_cycle'], 1);
    assert.equal(imported.expansion.simulation.sites['steam.oni.nursery_tray'].owner, 'player');
    proof.record('Native file import restores the earlier actual pending round and completes its single harvest once at the retained tray.');
    fs.writeFileSync(`${proof.output}/finished.json`, JSON.stringify(imported, null, 2));
    assert.deepEqual(proof.errors, []);
    await proof.finish(['Generated unlocked Shack, supplies, crafting access and high Cooking skill isolate the consumer; natural acquisition and balance acceptance are not proved.', 'Hands/roof loss during a pending round and malformed import have bounded reducer/validator coverage; separate browser branches remain open.']);
})().catch(async error => {if (proof) await proof.fail(error); console.error(error); process.exit(1);});
