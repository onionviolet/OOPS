const L = 'Bench clearance study';
const out = {before:brief(await save())};
out.trialKey = await keyAct(L, 'Try the difficult reading');
const pending = await stored();
check(pending.expansion.simulation.jobs.some(j=>j.commandId==='steam.boh.trial'), 'real trial pending');
out.trialPending = brief(pending);
await waitJobs();
let s = await stored();
out.diagnostic = s.expansion.simulation.knowledge.player['steam.boh.diagnostic'];
out.fatigue = s.expansion.simulation.conditions.player['steam.boh.study_fatigue'];
check(out.fatigue && out.fatigue.expiresAt > s.expansion.clock, 'four-minute fatigue visible before expiry');
check(/missing edge-clearance comparison/.test(out.diagnostic.value), 'specific diagnostic');
check(n(s,'Bench clearance manual')===out.before.inv['Bench clearance manual'] && n(s,'Sound repair stave')===4, 'manual and sample returned');
check(!s.expansion.actors.player.facts['steam.boh.procedureVersion'], 'diagnostic did not teach procedure');
out.restKey = await keyAct(L, 'Rest from clearance study');
out.restPending = brief(await stored());
await waitJobs(); s=await stored();
check(!s.expansion.simulation.conditions.player['steam.boh.study_fatigue'], 'rest clears fatigue');
out.rested = brief(s);
out.compareKey = await keyAct(L, 'Resolve the missing clearance comparison');
await waitJobs(); s=await stored();
check(s.expansion.actors.player.facts['steam.boh.preparationVersion']===1, 'comparison prepares');
check(!s.expansion.actors.player.facts['steam.boh.procedureVersion'], 'preparation is not learning');
out.prepared = await checkpoint2('current-fa10-prepared');
out.readKey = await keyAct(L, 'Read the prepared manual', 'Space');
await waitJobs(); s=await stored();
check(s.expansion.actors.player.facts['steam.boh.procedureVersion']===1, 'separate reading learns procedure');
check(n(s,'Bench clearance manual')===out.before.inv['Bench clearance manual'], 'same counted manual returned after read');
out.learned = await checkpoint2('current-fa10-learned');
out.end = brief(await stored());
await record('current-study', out);
return out;
