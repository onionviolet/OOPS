// MG02 natural: buy logs, buy room, repair, rental stay (use change blocked meanwhile), tenant request, repair answer, personal rest.
const a = (await snap('MG02 before')).st;
for (let i = 0; i < 12; i++) await h.mg('Buy one Rough wood log');
const logs = await snap('MG02 bought 12 logs');
expect(logs.st.money === a.money - 24 && logs.st.npc['mg.mira'].stock['{"id":"Rough wood log"}'] === 8, 'logs moved from Mira stock for 2 each');
await h.mg('Buy Mira’s one room concession');
await h.mg('Repair the room');
await idle();
const repaired = await snap('MG02 repaired');
expect(repaired.st.facts['mg.roomRepaired'] === true && repaired.st.money === a.money - 29, 'room bought and repaired');
await h.mg('Prepare the room for rental');
await h.mg('Host Sela for one rental period');
const staying = await snap('MG02 Sela staying');
const blocked = (await rows()).filter(r => /Use the room as a workshop|Prepare the room as an inn/.test(r));
expect(blocked.length && blocked.every(r => r.startsWith('[x]')), 'use change blocked during committed stay: ' + JSON.stringify(blocked));
await idle();
const paid = await snap('MG02 stay complete');
expect(paid.st.money === repaired.st.money + 2 && paid.st.npc['mg.sela'].coins === 38, 'Sela paid 2 at completion');
await h.mg('Hear Sela’s one room request');
await h.mg('Answer Sela’s request');
await idle();
const answered = await snap('MG02 request answered');
expect(answered.st.facts['mg.roomTenantRequest'] === false, 'request closed');
await h.mg('Use the room personally');
const tired = answered.s.character.stamina_to_full;
await h.mg('Rest in your repaired private room');
await idle();
const rested = await snap('MG02 private rest');
return {blocked, staminaToFullBefore: tired, staminaToFullAfter: rested.s.character.stamina_to_full, steps: journal.slice(-7).map(j => [j.label, j.money, j.npc['mg.sela'].coins, j.facts['mg.roomUse'], JSON.stringify(j.inventory), j.jobs.length])};
