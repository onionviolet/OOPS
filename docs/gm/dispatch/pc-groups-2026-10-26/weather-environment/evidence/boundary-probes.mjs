import assert from 'node:assert/strict';
import {settlePlace} from '../../../../../../src/owned_place_clock.js';
import {advanceHomeCondition,newHomeCondition} from '../../../../../../src/home_building_model.js';
import {isRainingAtMinute} from '../../../../../../src/weather_calendar.js';
const results=[];
const initial={id:'cottage',status:'stilled',ratio:.25,at:0,age:0,drift:0,stilledUntil:1440,larder:[]};
const long=settlePlace(initial,4);
let split=structuredClone(initial);
for(let at=1;at<=4;at++)split=settlePlace(split,at);
assert.equal(long.age,1);assert.equal(split.age,0);
results.push({probe:'P1 place clock partition',long:{age:long.age,drift:long.drift},split:{age:split.age,drift:split.drift},result:'reproduced mismatch'});
const start=4*1440-30;
const weatherAt=at=>({raining:isRainingAtMinute(start+at)});
const a={id:'shelter',condition:newHomeCondition(0)},b=structuredClone(a);
advanceHomeCondition(a,{clock:60,weatherAt});
advanceHomeCondition(b,{clock:30,weatherAt});advanceHomeCondition(b,{clock:60,weatherAt});
assert.equal(a.condition.wetness,0);assert.equal(b.condition.wetness,60);
results.push({probe:'P2 native rain boundary offset 30 min from root-hour boundary',long:a.condition,split:b.condition,result:'reproduced mismatch'});
console.log(JSON.stringify(results,null,2));
