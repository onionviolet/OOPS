test('owner ideas resolve immutable exact references and reject unknown, private and escaped targets',t=>{
    const root=ideaFixture(t),page=readOwnerIdeas(root,'docs/GAMEPLAY_BACKLOG.md'),row=page.rows[0];
    assert.equal(readOwnerIdeas(root,row.reference).rows[0].id,row.id);
    assert.throws(()=>readOwnerIdeas(root,row.reference,{idea:'0'.repeat(64)}),error=>error.status===400);
    assert.equal(readOwnerIdeas(root,'docs/GAMEPLAY_BACKLOG.md',{idea:row.id}).documentHash,page.documentHash);
    assert.throws(()=>readOwnerIdeas(root,'docs/GAMEPLAY_BACKLOG.md',{idea:'0'.repeat(64)}),error=>error.status===404);
    for(const path of ['docs/private/BACKLOG.md','docs/../outside.md','docs/%2e%2e/outside.md','docs\\GAMEPLAY_BACKLOG.md','C:/outside.md','docs/UNLISTED.md'])assert.throws(()=>readOwnerIdeas(root,path));
    assert.deepEqual(readOwnerIdeas(root,'docs/GAMEPLAY_BACKLOG.md').rows.map(row=>row.code),['N2']);
});

test('a backlog source check separates exact-entry identity from unrelated owner drift',t=>{
    const root=ideaFixture(t),page=readOwnerIdeas(root,'docs/GAMEPLAY_BACKLOG.md'),row=page.rows[0];
    const entry={source:{kind:'idea-owner',ideaId:row.id,reference:row.reference,ownerReference:row.ownerReference,documentHash:page.documentHash}};
    assert.equal(compareIdeaHandoffSource(entry,page),'matched');
    assert.equal(compareIdeaHandoffSource(entry,{...page,documentHash:'changed'}),'owner-changed');
    assert.equal(compareIdeaHandoffSource(entry,{...page,rows:[] }),'changed');
    assert.equal(compareIdeaHandoffSource(entry,{...page,rows:[{...row,reference:'docs/OTHER.md#idea-'+row.id}]}),'changed');
});

test('a saved exact idea reference remains an immutable owner citation when source wording changes',async t=>{
    const root=ideaFixture(t),idea=readOwnerIdeas(root,'docs/GAMEPLAY_BACKLOG.md').rows[0];
    const page={key:'fixture',world:'hp',prefix:'fixture',pass:'manual',kind:'rules',inspected:true,contentHash:'version',records:[{key:'r',href:'#world/hp/things/r',fileLines:[1],label:'Fixture record',type:'rule'}]};
    const packet=prepareHandoff({recordKey:'r',contentHash:'version',recordRoute:page.records[0].href,fileLines:[1],backlog:idea.reference,change:'Use one learned method.',check:'Observe its useful result.'},page);
    await saveHandoff(join(root,'queue'),packet);
    writeFileSync(join(root,'docs/GAMEPLAY_BACKLOG.md'),'# Gameplay\n## Proposed\n| Code | Idea | Boundary |\n|---|---|---|\n| N2 | Changed proposal wording | Proposed |\n');
    const queue=await readHandoffs(join(root,'queue'));
    assert.equal(queue.entries[0].proposal.backlog,idea.reference);
    assert.equal(handoffsForIdea(idea,[...queue.entries,{proposal:{backlog:'docs/GAMEPLAY_BACKLOG.md; N2'}}]).length,1,'a legacy unqualified code is not silently remapped to the new exact row');
    assert.throws(()=>readOwnerIdeas(root,queue.entries[0].proposal.backlog),error=>error.status===404);
    const owners=readIdeaOwners(root,queue.entries);
    assert(!owners.some(owner=>owner.reference.includes('#idea-')),'exact ideas do not become invented owner-section rows');
    assert.equal(handoffsForOwner({reference:'docs/GAMEPLAY_BACKLOG.md'},queue.entries,owners).length,1);
});

test('typed multi-reference handoffs admit public cited owners without altering packet text',t=>{
    const root=mkdtempSync(join(tmpdir(),'atlas-owner-cites-'));t.after(()=>rmSync(root,{recursive:true,force:true}));
    mkdirSync(join(root,'docs/private'),{recursive:true});mkdirSync(join(root,'docs/gm'));
    writeFileSync(join(root,'docs/IDEA_INDEX.md'),'## Ideas\n');
    writeFileSync(join(root,'docs/MAKING_RULES.md'),'# Making');
    writeFileSync(join(root,'docs/gm/READ_AHEAD_USE_2026-11-08.md'),'# Read ahead');
    writeFileSync(join(root,'docs/private/BACKLOG.md'),'# Hidden');
    const backlog='MR10/MR13/MR25-MR27/MR32; docs/MAKING_RULES.md; RA21 in READ_AHEAD_USE_2026-11-08.md';
    const packet={proposal:{backlog}};
    const rows=readIdeaOwners(root,[packet,{proposal:{backlog:'docs/private/BACKLOG.md; docs/missing.md; ../outside.md'}}]);
    assert.deepEqual(rows.map(row=>row.reference).sort(),['docs/MAKING_RULES.md','docs/gm/READ_AHEAD_USE_2026-11-08.md']);
    for(const row of rows)assert.deepEqual(handoffsForOwner(row,[packet],rows),[packet]);
    assert.equal(packet.proposal.backlog,backlog);
    assert.deepEqual(ownerReferenceTokens('docs/private/BACKLOG.md; docs/sealed/Ideas.md; ../outside.md; https://x/docs/A.md'),[]);
});

test('citation lookup respects full tokens, anchor scope and ambiguous filenames',()=>{
    const owners=['docs/A.md','docs/A.md#rivals','docs/AA.md','docs/x/SAME.md','docs/y/SAME.md'].map(reference=>({reference}));
    const entry=backlog=>({proposal:{backlog}});
    const exact=entry('docs/A.md#rivals; docs/AA.md'),broad=entry('docs/A.md'),ambiguous=entry('SAME.md'),lookalike=entry('docs/A.md.old; docs/AA.md#rivals');
    assert.deepEqual(handoffsForOwner(owners[0],[exact,broad,lookalike],owners),[exact,broad]);
    assert.deepEqual(handoffsForOwner(owners[1],[exact,broad,lookalike],owners),[exact]);
    assert.deepEqual(handoffsForOwner(owners[3],[ambiguous],owners),[]);
});
