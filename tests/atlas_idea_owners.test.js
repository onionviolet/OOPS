test('a real uncoded acceptance entry saves only in a fixture and longer exact refs share one contract',async t=>{
    const root=ideaFixture(t),owner='docs/gm/artifact-collection/ACCEPTANCE_BACKLOG.md';
    const actual=readOwnerIdeas(process.cwd(),owner).rows.find(row=>row.code===null);
    assert(actual);assert.equal(actual.kind,'acceptance-check');assert.match(actual.excerpt,/seller\/native bag\/money\/stock/);
    const source={key:'fixture',world:'fixture',prefix:'fixture',pass:'fixture',kind:'rules',inspected:true,contentHash:'fixture',records:[{key:'r',href:'#world/fixture/things/r',fileLines:[1],label:'Fixture only',type:'rule'}]};
    const request={recordKey:'r',contentHash:'fixture',recordRoute:source.records[0].href,fileLines:[1],backlog:actual.reference,change:'Record an existing acceptance check.',check:'Retain its source identity.'};
    await saveHandoff(join(root,'uncoded-queue'),prepareHandoff(request,source));
    assert.equal((await readHandoffs(join(root,'uncoded-queue'))).entries[0].proposal.backlog,actual.reference);
    const long=parseOwnerIdeas('N2: Retain this exact reference','docs/'+('a'.repeat(160))+'.md')[0].reference;
    assert(long.length>160&&long.length<CITED_REFERENCE_LIMIT);
    assert.equal(prepareHandoff({...request,backlog:long},source).proposal.backlog,long);
    assert.throws(()=>prepareHandoff({...request,backlog:'x'.repeat(CITED_REFERENCE_LIMIT+1)},source));
});

test('an indexed public alias cannot expose an outside or private idea target',t=>{
    const root=ideaFixture(t);mkdirSync(join(root,'outside'));writeFileSync(join(root,'outside/IDEAS.md'),'N1: outside');
    symlinkSync(join(root,'outside'),join(root,'docs/linked'),process.platform==='win32'?'junction':'dir');
    symlinkSync(join(root,'docs/private'),join(root,'docs/public-alias'),process.platform==='win32'?'junction':'dir');
    writeFileSync(join(root,'docs/IDEA_INDEX.md'),'[outside](linked/IDEAS.md) [private alias](public-alias/BACKLOG.md)');
    assert.throws(()=>readOwnerIdeas(root,'docs/linked/IDEAS.md'),error=>error.status===403);
    assert.throws(()=>readOwnerIdeas(root,'docs/public-alias/BACKLOG.md'),error=>error.status===403);
});

