import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,writeFileSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {readIdeaOwners} from '../prototypes/world-atlas/idea-owners.mjs';
import {readOwnerIdeas} from '../prototypes/world-atlas/owner-ideas.mjs';
import {searchOwnerIdeas} from '../prototypes/world-atlas/owner-idea-search.mjs';

function fixture(t){
    const root=mkdtempSync(join(tmpdir(),'atlas-idea-search-'));t.after(()=>rmSync(root,{recursive:true,force:true}));mkdirSync(join(root,'docs/private'),{recursive:true});
    writeFileSync(join(root,'docs/IDEA_INDEX.md'),'[Game](GAME_BACKLOG.md) [Same section](GAME_BACKLOG.md#proposals) [Other](OTHER_IDEAS.md#proposals) [Private](private/HIDDEN_BACKLOG.md)');
    writeFileSync(join(root,'docs/GAME_BACKLOG.md'),'# Game\n## Proposals\n| Code | Idea | Check |\n|---|---|---|\n| N2 | Use an earned method at work | Observe its useful result |\n| N20 | A different method mentioning N2 | Remains distinct |\n- Use a real gear substitute in the method.\n');
    writeFileSync(join(root,'docs/OTHER_IDEAS.md'),'# Other\n## Proposals\n| Code | Idea | Check |\n|---|---|---|\n| N2 | Give the method a different consumer | Observe its own result |\n');
    writeFileSync(join(root,'docs/METRIC_BACKLOG.md'),'# Metrics\nGenerated by `node check`.\n## Measured\n| Start | Presses |\n|---|---|\n| method | 100 |\n## Policy limits\n- This method policy definition is metadata, not an entry.');
    writeFileSync(join(root,'docs/private/HIDDEN_BACKLOG.md'),'# Secret\nN2: Secret method never included');
    writeFileSync(join(root,'docs/UNLISTED.md'),'N2: Unlisted method never included');return root;
}

test('one request-local directory admission covers deduplicated owners and exact codes across sources',t=>{
    const root=fixture(t),inventory=readIdeaOwners(root);let directoryCalls=0,reads=0;
    const result=searchOwnerIdeas(root,'N2',{limit:1,readDirectory:()=>{directoryCalls++;return inventory;},readOwner:(r,file,options)=>{reads++;assert.equal(options.allowedOwners,inventory);return readOwnerIdeas(r,file,options);}});
    assert.equal(directoryCalls,1);assert.equal(reads,3);assert.equal(result.ownerFilesSearched,3);
    assert.equal(result.total,2);assert.equal(result.rows.length,1);assert.equal(result.exactCode,true);
    const next=searchOwnerIdeas(root,'n2',{offset:1,limit:1});assert.equal(next.total,2);assert.notEqual(next.rows[0].id,result.rows[0].id);
    assert.notEqual(next.rows[0].ownerReference,result.rows[0].ownerReference);
});

test('keyword search excludes private, unlisted and metric/policy rows while retaining source labels',t=>{
    const root=fixture(t),result=searchOwnerIdeas(root,'method');
    assert.equal(result.total,4);assert(result.rows.every(row=>row.kind==='feature-proposal'));
    assert(!result.rows.some(row=>/private|UNLISTED|METRIC/.test(row.ownerReference)));
    assert.equal(searchOwnerIdeas(root,'Secret').total,0);assert.equal(searchOwnerIdeas(root,'100').total,0);
    assert(result.rows.every(row=>row.reference.includes('#idea-')&&row.documentHash));
});

test('an exact result is rechecked on open and changed wording cannot inherit its old source ID',t=>{
    const root=fixture(t),before=searchOwnerIdeas(root,'N2'),old=before.rows.find(row=>row.ownerReference==='docs/GAME_BACKLOG.md');
    writeFileSync(join(root,'docs/GAME_BACKLOG.md'),'# Game\n## Proposals\n| Code | Idea | Check |\n|---|---|---|\n| N2 | A changed method proposal | New source wording |\n');
    assert.throws(()=>readOwnerIdeas(root,old.reference),error=>error.status===404);
    const after=searchOwnerIdeas(root,'N2');assert.equal(after.total,2);
    assert(!after.rows.some(row=>row.id===old.id));
    assert.equal(after.rows.find(row=>row.ownerReference==='docs/OTHER_IDEAS.md').id,before.rows.find(row=>row.ownerReference==='docs/OTHER_IDEAS.md').id);
});

test('empty and overlong queries or unbounded pages refuse before scanning owners',t=>{
    const root=fixture(t);let scans=0;const readDirectory=()=>{scans++;return [];};
    for(const query of ['', ' ', 'x'.repeat(121)])assert.throws(()=>searchOwnerIdeas(root,query,{readDirectory}),error=>error.status===400);
    for(const options of [{limit:0},{limit:51},{offset:-1},{offset:1.5}])assert.throws(()=>searchOwnerIdeas(root,'method',{...options,readDirectory}),error=>error.status===400);
    assert.equal(scans,0);
});

test('source-kind filtering preserves classification, totals and pagination without changing the default',t=>{
    const root=fixture(t);
    writeFileSync(join(root,'docs/OTHER_IDEAS.md'),'# Other\n## Proposals\nN2: A method proposal\n## Acceptance checks\nA1: A method check, execution not inferred\n## Completed history\nH1: A method report from history\n');
    writeFileSync(join(root,'docs/FINDING_BACKLOG.md'),'Generated by test.\n# Findings\nF1: A method observed in a report\n');
    writeFileSync(join(root,'docs/NEUTRAL_BACKLOG.md'),'# Neutral\nB1: A method entry without classification\n');
    const all=searchOwnerIdeas(root,'method',{limit:50});
    assert.deepEqual(searchOwnerIdeas(root,'method',{limit:50,kind:''}),all);
    const kinds=['feature-proposal','acceptance-check','finding','historical-note','backlog-entry'];
    let total=0;
    for(const kind of kinds){
        const filtered=searchOwnerIdeas(root,'method',{kind,limit:50});
        assert.ok(filtered.total>0,kind);assert.equal(filtered.kind,kind);
        assert.equal(filtered.total,all.rows.filter(row=>row.kind===kind).length);
        assert(filtered.rows.every(row=>row.kind===kind));
        assert.deepEqual(filtered.rows,all.rows.filter(row=>row.kind===kind));total+=filtered.total;
    }
    assert.equal(total,all.total);
    const proposals=searchOwnerIdeas(root,'method',{kind:'feature-proposal',limit:50});
    const page=searchOwnerIdeas(root,'method',{kind:'feature-proposal',offset:1,limit:1});
    assert.equal(page.total,proposals.total);assert.deepEqual(page.rows,[proposals.rows[1]]);
    assert.equal(searchOwnerIdeas(root,'N2',{kind:'acceptance-check'}).total,0);
    assert.equal(searchOwnerIdeas(root,'N2',{kind:'feature-proposal'}).total,2);
});

test('unsupported source kinds refuse before owner scanning rather than inventing acceptance states',()=>{
    let scans=0;
    for(const kind of ['accepted','proposal','all',null,[],7])assert.throws(()=>searchOwnerIdeas('.', 'method',{kind,readDirectory:()=>{scans++;return [];}}),error=>error.status===400);
    assert.equal(scans,0);
});
