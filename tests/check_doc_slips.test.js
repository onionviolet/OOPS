import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync, mkdirSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const repo = fileURLToPath(new URL('..', import.meta.url));
const script = join(repo, 'scripts/check_doc_slips.mjs');

test('doc slip lint accepts compliant additions and flags the two bad additions', () => {
  const dir = mkdtempSync(join(tmpdir(), 'doc-slips-'));
  const prepare = (text) => {
    mkdirSync(join(dir, 'docs'), {recursive: true});
    writeFileSync(join(dir, 'docs/sample.md'), text);
    const init = spawnSync('git', ['init', '-q'], {cwd: dir});
    assert.equal(init.status, 0);
    spawnSync('git', ['add', '.'], {cwd: dir});
    spawnSync('git', ['-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.test', 'commit', '-qm', 'base'], {cwd: dir});
    return () => spawnSync(process.execPath, [script, '--base', 'HEAD'], {cwd: dir, encoding: 'utf8'});
  };
  try {
    const run = prepare('# Fixture\n');
    writeFileSync(join(dir, 'docs/sample.md'), '# Fixture\n\n- By default, the rule applies unless a world dial changes it.\n- This behavior is accepted [owner](../PROJECT.md) AD5.\n');
    let result = run();
    assert.equal(result.status, 0, result.stderr);
    writeFileSync(join(dir, 'docs/sample.md'), '# Fixture\n\n- The rule always applies.\n- This behavior is accepted.\n');
    result = run();
    assert.equal(result.status, 1);
    assert.equal((result.stderr.match(/docs\/sample\.md:/g) ?? []).length, 2, result.stderr);
    assert.match(result.stderr, /absolute rule word/);
    assert.match(result.stderr, /acceptance claim/);
    writeFileSync(join(dir, 'docs/sample.md'), '# Fixture\n');
    writeFileSync(join(dir, 'docs/new.md'), '- The rule always applies.\n');
    result = run();
    assert.equal(result.status, 1);
    assert.match(result.stderr, /docs\/new.md:1:/);
    rmSync(join(dir, 'docs/new.md'));
    writeFileSync(join(dir, 'docs/sample.md'), '# Fixture\n');
    const clean = spawnSync(process.execPath, [script], {cwd: dir, encoding: 'utf8'});
    assert.equal(clean.status, 0, clean.stderr);
  } finally { rmSync(dir, {recursive: true, force: true}); }
});

test('lint distinguishes metadata and scoped language without hiding new adoption or universal claims', () => {
  const dir = mkdtempSync(join(tmpdir(), 'doc-slips-context-'));
  try {
    mkdirSync(join(dir, 'docs/research'), {recursive: true});
    assert.equal(spawnSync('git', ['init', '-q'], {cwd: dir}).status, 0);
    const file = join(dir, 'docs/context.md');
    const run = () => spawnSync(process.execPath, [script], {cwd: dir, encoding: 'utf8'});
    writeFileSync(file, [
      '- The source remains read-only; coverage is chapter-only.',
      '- Show the event only when the actor witnessed it.',
      '- The contract has accepted terms and an accepted price.',
      'Keep the existing accepted direction and scope.',
      'This is not a newly accepted decision.',
      'No fan interpretation is accepted by this request.',
    ].join('\n'));
    const catalogue = join(dir, 'docs/research/SOURCE_LIBRARY_CATALOGUE.md');
    writeFileSync(catalogue, 'Generated by `scripts/library_catalogue.py`\n\n| Title | Author | Kind | Lang | Hash |\n| Book | Always RollsAOne | epub | en | 123456abcd |\n');
    let result = run();
    assert.equal(result.status, 0, result.stderr);
    writeFileSync(file, '- This rule always applies, including only when selected.\nThis is accepted direction.\n');
    result = run();
    assert.equal(result.status, 1);
    assert.match(result.stderr, /absolute rule word/);
    assert.match(result.stderr, /acceptance claim/);
    writeFileSync(file, '- The rule always applies. <!-- slip-ok: Explicit fixture exception for this exact line. -->\n- The next rule always applies.\n');
    result = run();
    assert.equal((result.stderr.match(/absolute rule word/g) ?? []).length, 1, result.stderr);
    assert.match(result.stderr, /context.md:2:/);
    writeFileSync(file, '# No issue\n');
    writeFileSync(catalogue, 'Generated by `scripts/library_catalogue.py`\n\n| Book | Always RollsAOne | epub | en | 123456abcd |\n- The gameplay rule always applies.\n');
    result = run();
    assert.equal(result.status, 1);
    assert.match(result.stderr, /SOURCE_LIBRARY_CATALOGUE.md:4:/);
  } finally { rmSync(dir, {recursive: true, force: true}); }
});
