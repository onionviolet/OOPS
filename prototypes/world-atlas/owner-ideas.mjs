import {createHash} from 'node:crypto';
import {readFileSync,realpathSync} from 'node:fs';
import {isAbsolute,relative,resolve,sep} from 'node:path';
import {readIdeaOwners} from './idea-owners.mjs';
import {CITED_REFERENCE_LIMIT} from './cited-reference-contract.mjs';

const hash=value=>createHash('sha256').update(value).digest('hex');
const plain=value=>value.replace(/\[([^\]]+)\]\([^)]*\)/g,'$1').replace(/<[^>]+>/g,'').replace(/[*`]/g,'').replace(/\\\|/g,'|').replace(/\s+/g,' ').trim();
const codeIn=value=>plain(value).match(/\b([A-Z]{1,8}\d+[a-z]?)\b/)?.[1];
const slug=value=>plain(value).toLocaleLowerCase().replace(/[^\p{L}\p{N}_ -]/gu,'').replace(/ /g,'-');

// A bounded reader for the project's coded Markdown tables, headings and paragraphs.
// The surrounding section and wording are part of identity; a code is not globally unique.
export function parseOwnerIdeas(text,owner) {
    const lines=text.split(/\r?\n/),headings=[],anchorCounts=new Map(),occurrences=new Map(),rows=[];
    const generated=/^Generated by /m.test(text),backlog=/backlog/i.test(owner);
    let fence=null,frontmatter=lines[0]?.trim()==='---',tableHeader=[];
    function sourceKind(format) {
        const context=headings.map(heading=>heading.title).join(' / ');
        if(/histor|completed|reconcil|checks performed|\.last\.md$/i.test(context+' '+owner))return ['historical-note','Historical/report note from source context'];
        if(format==='finding'||generated)return ['finding','Reported finding, not a feature proposal'];
        for(const heading of [...headings].reverse()){
            if(/propos|idea palette|later\s*\/\s*delegate|feature ideas/i.test(heading.title))return ['feature-proposal','Proposal entry from source context'];
            if(/acceptance|behavioral gates|remaining gates/i.test(heading.title))return ['acceptance-check','Acceptance check from source backlog; execution status is not inferred'];
        }
        if(/acceptance|behavioral gates|remaining gates/i.test(context+' '+owner))return ['acceptance-check','Acceptance check from source backlog; execution status is not inferred'];
        if(/propos|idea palette|later\s*\/\s*delegate|feature ideas/i.test(context))return ['feature-proposal','Proposal entry from source context'];
        return ['backlog-entry','Structured backlog entry; status unclassified'];
    }
    function add(code,title,wording,start,end,excerpt=wording,format='coded') {
        const section=headings.map(heading=>heading.title),sectionAnchor=headings.at(-1)?.anchor||'';
        const content=wording.trim(),key=JSON.stringify([section,code,content]),occurrence=occurrences.get(key)||0;
        occurrences.set(key,occurrence+1);
        const id=hash(JSON.stringify([owner,section,code,content,occurrence]));
        const reference=owner+'#idea-'+id;
        const [kind,entryLabel]=sourceKind(format);
        rows.push({id,code,title:plain(title).slice(0,240),excerpt:plain(excerpt).slice(0,600),section,sectionAnchor,
            kind,entryLabel,format,
            sectionAnchors:headings.map(heading=>heading.anchor),lineStart:start+1,lineEnd:end+1,
            ownerReference:owner,reference,sourceReference:owner+'#L'+(start+1),citable:reference.length<=CITED_REFERENCE_LIMIT});
    }
    for(let i=0;i<lines.length;i++) {
        const line=lines[i],marker=/^\s*(`{3,}|~{3,})/.exec(line);
        if(frontmatter){if(i>0&&line.trim()==='---')frontmatter=false;continue;}
        if(marker){if(!fence)fence=marker[1][0];else if(fence===marker[1][0])fence=null;continue;}
        if(fence)continue;
        const heading=/^(#{1,6})\s+(.+?)(?:\s+#+)?$/.exec(line);
        if(heading){
            tableHeader=[];
            const level=heading[1].length,title=plain(heading[2]),base=slug(title),count=anchorCounts.get(base)||0;
            anchorCounts.set(base,count+1);while(headings.length&&headings.at(-1).level>=level)headings.pop();
            headings.push({level,title,anchor:base+(count?'-'+count:'')});
            const code=/^(?:[A-Z]{1,8}\d+[a-z]?)(?=\s*[:.,·–—-])/.exec(title)?.[0];
            if(code)add(code,title,line,i,i);
            continue;
        }
        if(/^\s*\|/.test(line)){
            const cells=line.trim().replace(/^\||\|$/g,'').split(/(?<!\\)\|/).map(cell=>cell.trim());
            if(/^\s*\|?\s*:?-{3}/.test(line))continue;
            const code=codeIn(cells[0]||'');
            if(code&&cells.length>1)add(code,cells[1]||cells[0],line,i,i,cells.slice(2).join(' · '));
            else if(lines[i+1]&&/^\s*\|\s*:?-{3}/.test(lines[i+1]))tableHeader=cells.map(plain);
            else if(backlog&&tableHeader.some(name=>/^(?:idea|proposal|check|acceptance|gate(?: family)?|finding|control|task|gap|follow.up)$/i.test(name))&&
                !headings.some(heading=>/^(?:measured|policy limits|words,|by world|metadata|recording)/i.test(heading.title))&&
                cells.some(cell=>plain(cell)&&!/^none$/i.test(plain(cell)))) {
                const titleIndex=tableHeader.findIndex(name=>/^(?:idea|proposal|check|acceptance|gate(?: family)?|finding|label|task|gap|follow.up)$/i.test(name));
                const title=plain(cells[titleIndex>=0?titleIndex:1]||'');
                if(title&&title.toLowerCase()!=='none')add(null,title,line,i,i,cells.join(' · '),generated?'finding':'table');
            }
            continue;
        }
        const paragraph=/^\s*(?:[-*+]\s+|\d+[.)]\s+)?(?:\*\*|`)?([A-Z]{1,8}\d+[a-z]?)(?:\*\*|`)?\s*[:.,–—]\s+(.+)$/.exec(line);
        if(paragraph){
            const start=i,parts=[line];
            while(i+1<lines.length&&lines[i+1].trim()&&!/^\s*(?:#|\||[-*+]\s|`{3}|~{3}|[A-Z]{1,8}\d+[a-z]?\s*[:.,])/.test(lines[i+1]))parts.push(lines[++i]);
            add(paragraph[1],paragraph[2],parts.join('\n'),start,i);
            continue;
        }
        // Bold code + state prefixes are present in saved delivery backlogs and summaries.
        const boldCode=/^\s*(?:[-*+]\s+|\d+[.)]\s+)?\*\*([A-Z]{1,8}\d+[a-z]?)([^*]*?):\*\*\s*(.+)$/.exec(line);
        if(boldCode){
            const start=i,parts=[line];
            while(i+1<lines.length&&/^\s{2,}\S/.test(lines[i+1])&&!/^\s*(?:#|\||[-*+]\s)/.test(lines[i+1]))parts.push(lines[++i]);
            add(boldCode[1],plain(boldCode[2]+' '+boldCode[3]),parts.join('\n'),start,i);continue;
        }
        const bullet=/^(\s*)(?:[-*+]\s+|\d+[.)]\s+)(?:\[([ xX])\]\s*)?(.+)$/.exec(line);
        const skipSection=headings.some(heading=>/^(?:measured|policy limits|words,|by world|metadata|recording|links|references|owners|source inventory|inputs)\b/i.test(heading.title));
        const rewriteFinding=/^L\d+\s+\*\*[^*]+\*\*:/.test(bullet?.[3]||'');
        if(!bullet||!backlog||skipSection||(generated&&!rewriteFinding))continue;
        const body=bullet[3];
        if(plain(body).length<12||/^(?:status|owner|scope|source|evidence|receipt|command|file|updated|generated|recording|rules|priority|links?|date|build|branch|commit|baseline|result)\s*:/i.test(plain(body)))continue;
        if(/^\[[^\]]+\]\([^)]*\)$/.test(body.trim())||/^`?(?:docs|src|scripts|tests)\/\S+`?$/.test(body.trim()))continue;
        const start=i,parts=[line],indent=bullet[1].length;
        while(i+1<lines.length){
            const next=lines[i+1];
            if(/^\s*(?:#|\||`{3}|~{3})/.test(next)||/^\s*(?:[-*+]\s+|\d+[.)]\s+)?(?:\*\*|`)?[A-Z]{1,8}\d+[a-z]?(?:\*\*|`)?\s*[:.,]/.test(next))break;
            const nextBullet=/^(\s*)(?:[-*+]\s+|\d+[.)]\s+)/.exec(next);
            if(nextBullet&&nextBullet[1].length<=indent)break;
            if(next.trim()&&next.match(/^\s*/)[0].length<=indent)break;
            if(!next.trim()&&(!lines[i+2]?.trim()||lines[i+2].match(/^\s*/)[0].length<=indent))break;
            parts.push(lines[++i]);
        }
        const clean=plain(parts.join('\n')).replace(/^(?:[-*+]|\d+[.)])\s*(?:\[[ xX]\]\s*)?/,''),title=clean.split(/(?<=[.!?])\s/)[0];
        add(null,title,parts.join('\n'),start,i,parts.join('\n'),rewriteFinding?'finding':'list');
    }
    return rows;
}

function refusal(message,status=400){const error=Error(message);error.status=status;return error;}
export function readOwnerIdeas(root,owner,{idea,allowedOwners}={}) {
    if(typeof owner!=='string'||owner.length>CITED_REFERENCE_LIMIT||/[\\%?\u0000-\u001f]/.test(owner))throw refusal('Choose a canonical public idea owner.');
    const [file,anchor,...extra]=owner.split('#'),parts=file.split('/');
    if(extra.length||parts[0]!=='docs'||!file.endsWith('.md')||parts.some(part=>!part||part.startsWith('.')||/private|sealed/i.test(part)))throw refusal('Choose a canonical public idea owner.');
    // Directory metadata is an allowlist. Do not inspect arbitrary docs or handoff-supplied owners.
    // A cross-owner search may reuse its one request-local inventory. Ordinary
    // lookup/submission calls still rebuild the canonical inventory on open.
    const allowed=allowedOwners||readIdeaOwners(root);
    const identity=/^idea-([a-f0-9]{64})$/.exec(anchor||'')?.[1],section=identity?null:anchor;
    if(identity&&idea&&identity!==idea)throw refusal('The exact reference and requested idea do not match.');
    if(!allowed.some(row=>section?row.reference===owner:row.reference.split('#')[0]===file))throw refusal('This document or section is not in the canonical public idea directory.',403);
    const docs=realpathSync(resolve(root,'docs')),target=realpathSync(resolve(root,file)),local=relative(docs,target);
    if(!local||isAbsolute(local)||local==='..'||local.startsWith('..'+sep)||local.split(sep).some(part=>part.startsWith('.')||/private|sealed/i.test(part)))throw refusal('The owner target is outside the public idea directory.',403);
    const bytes=readFileSync(target),documentHash=hash(bytes),rows=parseOwnerIdeas(bytes.toString('utf8'),file).filter(row=>!section||row.sectionAnchors.includes(section));
    if(realpathSync(resolve(root,file))!==target)throw refusal('The owner target changed. Reopen it.',409);
    const selected=idea||identity;
    if(selected&&(!/^[a-f0-9]{64}$/.test(selected)||!rows.some(row=>row.id===selected)))throw refusal('This exact idea is absent or its wording/section changed. Browse the current owner.',404);
    return {owner,documentHash,rows:selected?rows.filter(row=>row.id===selected):rows,
        boundary:'Structured entries from this owner, including source acceptance checks, proposal-context entries, reported findings and historical notes. Their wording is retained; no open-work, accepted-decision or completion status is inferred.'};
}
