#!/usr/bin/env node
// Player-text vocabulary lint (PRS5/PRS6, docs/PROSE_RULES.md). Scans string
// fields that reach the player (description, text, label, reason, ...) in
// src/*.js for rulebook and engine vocabulary ("admitted", "native", "seam",
// "actual", ...). Those words are how agents talk to each other, not how
// Tingen or the Village talks to the player.
//
// Ratchet: scripts/player_text_baseline.json lists the hits that already
// shipped (file + sha of the string). Known hits pass; a new one fails. Rewrite
// a string and its baseline entry simply stops matching, so the backlog only
// shrinks. Regenerate with --update-baseline after a rewrite pass.
//
//   node scripts/check_player_text.mjs                 check (exit 1 on new hits)
//   node scripts/check_player_text.mjs --update-baseline
//   node scripts/check_player_text.mjs --backlog       write docs/prose/PROSE_REWRITE_BACKLOG.md
//
// Allow one line with a trailing comment: // player-text: allow <why>
import {createHash} from 'node:crypto';
import {existsSync, readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {resolve, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const baselinePath = resolve(root, 'scripts/player_text_baseline.json');
const backlogPath = resolve(root, 'docs/prose/PROSE_REWRITE_BACKLOG.md');
const args = new Set(process.argv.slice(2));

// Words that are almost always the engine talking. In-world uses (a shop
// receipt, the owner of a stall) get a `player-text: allow` comment.
export const ENGINE_WORDS = [
  'admitted', 'native', 'actual', 'actually', 'seam', 'consumer', 'producer', 'read model',
  'fact id', 'facts? frame', 'proposal', 'proposed', 'topology', 'identity-owned',
  'identity-local', 'supported measure', 'denominator', 'fixture', 'baseline',
  'canon label', 'counter operation', 'bounded', 'revalidat\\w*', 'eligib\\w*',
  'disclosed', 'owned kit', 'own log', 'cited slice', 'the slice', 'this slice',
  'runtime', 'registry', 'host\\b', 'adapter', 'validated', 'atomically',
  // PX47 (2026-11-10 playtest): prototype talk and hedges that reached the player.
  'prototype', 'represented', 'authority-backed', 'played minutes', 'makes no claim', 'past history', 'text not found',
];
const wordRe = new RegExp(`\\b(${ENGINE_WORDS.join('|')})\\b`, 'i');
// Field names whose string values the player reads.
const FIELDS = 'description|text|label|title|reason|summary|line|body|flavour|flavor|note|hint|quote|name|tooltip|caption|message|blocked|why';
const fieldRe = new RegExp(`\\b(?:${FIELDS})\\s*:\\s*(["'\`])((?:\\\\.|(?!\\1)[^\\\\\\n])*)\\1`, 'g');
// PX47: text set straight on a node (`intro.textContent = '...'`, `a ? '...' : ...`) reaches the player the same way.
const assignRe = /\b(?:textContent|innerText)\s*=\s*(?:[^;\n]*?[?:]\s*)?(["'`])((?:\\.|(?!\1)[^\\\n])*)\1/g;
const MIN_LEN = 25;

const sha = s => createHash('sha256').update(s).digest('hex').slice(0, 12);

export function scanSource(name, source) {
  const hits = [];
  const lineStarts = [0];
  for (let i = 0; i < source.length; i++) if (source[i] === '\n') lineStarts.push(i + 1);
  const lineOf = idx => { let lo = 0, hi = lineStarts.length - 1; while (lo < hi) { const mid = (lo + hi + 1) >> 1; if (lineStarts[mid] <= idx) lo = mid; else hi = mid - 1; } return lo; };
  for (const m of [...source.matchAll(fieldRe), ...source.matchAll(assignRe)]) {
    const text = m[2];
    if (text.length < MIN_LEN) continue;
    const word = text.match(wordRe);
    if (!word) continue;
    const ln = lineOf(m.index);
    const lineText = source.slice(lineStarts[ln], lineStarts[ln + 1] ?? source.length);
    if (/player-text:\s*allow/.test(lineText)) continue;
    hits.push({file: name, line: ln + 1, word: word[1].toLowerCase(), text, key: `${name}:${sha(text)}`});
  }
  return hits;
}

export function scanTree() {
  const hits = [];
  for (const name of readdirSync(resolve(root, 'src')).filter(f => f.endsWith('.js')).sort()) {
    hits.push(...scanSource(`src/${name}`, readFileSync(resolve(root, 'src', name), 'utf8')));
  }
  return hits;
}

function writeBacklog(hits) {
  const byFile = new Map();
  for (const h of hits) (byFile.get(h.file) || byFile.set(h.file, []).get(h.file)).push(h);
  const files = [...byFile.entries()].sort((a, b) => b[1].length - a[1].length);
  const wordCounts = new Map();
  for (const h of hits) wordCounts.set(h.word, (wordCounts.get(h.word) || 0) + 1);
  const out = [];
  out.push('# Prose rewrite backlog');
  out.push('');
  out.push(`Generated by \`node scripts/check_player_text.mjs --backlog\`. ${hits.length} player-facing strings in ${files.length} files still use engine vocabulary ([PRS6](../PROSE_RULES.md)). Rewrite by surface (confirm screens and tooltips, then Reports lines, then reference text), not by file; a rewrite changes the owning content string only and leaves saved observations alone (UR74). Regenerate after each pass; the baseline ratchet keeps new hits out.`);
  out.push('');
  out.push('## Words, most frequent first');
  out.push('');
  out.push('| Word | Hits |');
  out.push('| --- | --- |');
  for (const [w, n] of [...wordCounts.entries()].sort((a, b) => b[1] - a[1])) out.push(`| ${w} | ${n} |`);
  out.push('');
  out.push('## Files, most hits first');
  out.push('');
  for (const [file, rows] of files) {
    out.push(`### ${file} (${rows.length})`);
    out.push('');
    // Quoted player text is evidence, not a rule; silence the doc-slip absolute-word check on it.
    for (const r of rows) out.push(`- L${r.line} **${r.word}**: ${r.text.replace(/\|/g, '\\|').slice(0, 160)}${r.text.length > 160 ? '…' : ''} <!-- slip-ok: quoted player text -->`);
    out.push('');
  }
  writeFileSync(backlogPath, out.join('\n'));
  return backlogPath;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const hits = scanTree();
  if (args.has('--backlog')) console.log(`wrote ${writeBacklog(hits)} (${hits.length} strings)`);
  if (args.has('--update-baseline')) {
    writeFileSync(baselinePath, JSON.stringify({generated: new Date().toISOString().slice(0, 10), keys: hits.map(h => h.key).sort()}, null, 0) + '\n');
    console.log(`baseline: ${hits.length} known hits`);
    process.exit(0);
  }
  const known = new Set(existsSync(baselinePath) ? JSON.parse(readFileSync(baselinePath, 'utf8')).keys : []);
  const fresh = hits.filter(h => !known.has(h.key));
  const present = new Set(hits.map(h => h.key));
  const retired = [...known].filter(k => !present.has(k)).length;
  console.log(`Player text check: ${hits.length} engine-vocabulary strings (${known.size} in baseline, ${retired} retired, ${fresh.length} new)`);
  for (const h of fresh) console.log(`  FAIL  ${h.file}:${h.line} "${h.word}": ${h.text.slice(0, 120)}`);
  if (fresh.length) console.log('  Rewrite in the player\'s words (docs/PROSE_RULES.md PRS6), or mark an in-world use with `// player-text: allow <why>`.');
  console.log(fresh.length ? `FAIL (${fresh.length} new)` : 'PASS');
  process.exit(fresh.length ? 1 : 0);
}
