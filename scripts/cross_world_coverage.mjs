// Regenerates the systems-by-world matrix from the coverage table in the cross-world task record, so the picture and the record
// cannot drift. Each cell shows both layers: F (foundation: the world plugs into the shared engine by data) and U (use in the world
// proper: walked natively at the AD43 floor). Usage: node scripts/cross_world_coverage.mjs [--check]
import {readFileSync, writeFileSync} from 'node:fs';
const RECORD = 'docs/gm/dispatch/cross-world-systems-2026-11-07/CHECKPOINT.md';
const OUT = 'prototypes/progress-atlas/2026-11-07-systems-by-world.html';
const md = readFileSync(RECORD, 'utf8');
const start = md.indexOf('## World × system coverage');
if(start < 0) throw Error('Coverage section missing from the task record.');
const lines = md.slice(start).split('\n').filter(l => l.startsWith('|'));
const cells = l => l.split('|').slice(1, -1).map(c => c.trim().replace(/\*\*/g, ''));
const [head, , ...body] = lines;
const cols = cells(head).slice(1);
const rows = [];
for(const l of body) {const c = cells(l); if(c.length !== cols.length + 1) break; rows.push(c);}
// "port / floor (LT8)" -> {f:'port', u:'floor', note}; "n/a ..." -> {na:true}.
const parse = raw => {
    if(/^n\/a\b/.test(raw)) return {f: 'na', u: 'na', raw};
    const [f, u = '-'] = raw.split('/').map(x => x.trim());
    const fk = /^port/.test(f) ? 'port' : /^own/.test(f) ? 'own' : /^thin/.test(f) ? 'thin' : 'nil';
    const uk = /^floor pending/.test(u) ? 'pending' : /^floor/.test(u) ? 'floor' : /^below/.test(u) ? 'below' : 'nil';
    return {f: fk, u: uk, raw};
};
const data = rows.map(r => [r[0], r.slice(1).map(parse)]);
const html = `<h2 class="sr-only">Deep systems by world, two layers per cell: F, the world plugs into the shared engine by data; U, the system is used in that world's ordinary play, walked natively. Generated from the cross-world task record.</h2>
<style>
.sy{font-size:12px;color:var(--text-primary)}.sy table{width:100%;border-collapse:collapse;table-layout:fixed}
.sy th{font-weight:400;color:var(--text-secondary);font-size:11px;padding:4px 2px;text-align:center}.sy th:first-child{width:150px;text-align:left}
.sy td{padding:3px 2px;border-bottom:.5px solid var(--border);text-align:center}.sy td:first-child{text-align:left}
.k{height:22px;border-radius:4px;font-size:10px;display:flex;cursor:pointer;overflow:hidden}.k b{flex:1;display:flex;align-items:center;justify-content:center;font-weight:400}
.port{background:#1baf7a;color:#04342c}.own{background:#fac775;color:#633806}.thin{border:1px solid var(--text-secondary);color:var(--text-secondary)}.nil{border:1px dashed var(--border-strong);color:var(--text-muted)}
.floor{background:#0f6e56;color:#e1f5ee}.pending{background:#5dcaa5;color:#04342c}.below{background:#ef9f27;color:#412402}.na{color:var(--text-muted);font-style:italic}
.lg{display:flex;gap:12px;flex-wrap:wrap;color:var(--text-secondary);font-size:11px;margin:8px 0}.lg span{display:flex;align-items:center;gap:5px}.lg i{width:16px;height:10px;border-radius:2px;display:inline-block}
.det{background:var(--surface-1);border-radius:8px;padding:10px 12px;margin:8px 0;color:var(--text-secondary);font-size:12px}
</style>
<div class="sy">
<div class="lg"><span>Left half F:</span><span><i class="port"></i>shared engine, world data</span><span><i class="own"></i>own version</span><span><i class="thin"></i>thin</span><span><i class="nil"></i>none</span><span>Right half U:</span><span><i class="floor"></i>walked at floor</span><span><i class="pending"></i>walk pending</span><span><i class="below"></i>below floor</span></div>
<table id="s"></table>
<div class="det" id="sd">Select a cell for what is there.</div>
<p style="color:var(--text-muted);font-size:11px">Generated by scripts/cross_world_coverage.mjs from docs/gm/dispatch/cross-world-systems-2026-11-07/CHECKPOINT.md. Six other book worlds: a static read of src/, not route proof.</p>
</div>
<script>
const C=${JSON.stringify(cols)};
const S=${JSON.stringify(data.map(([n, cs]) => [n, cs.map(c => [c.f, c.u, c.raw])]))};
const F={port:'port',own:'own',thin:'thin',nil:'-',na:'n/a'},U={floor:'floor',pending:'walk',below:'below',nil:'-',na:''};
let h='<tr><th>System</th>'+C.map(c=>'<th>'+c+'</th>').join('')+'</tr>';
S.forEach((r,i)=>{h+='<tr><td>'+r[0]+'</td>'+r[1].map((v,j)=>v[0]==='na'?'<td><div class="k na" tabindex="0" data-i="'+i+'" data-j="'+j+'"><b>n/a</b></div></td>':'<td><div class="k" tabindex="0" data-i="'+i+'" data-j="'+j+'"><b class="'+v[0]+'">'+F[v[0]]+'</b><b class="'+v[1]+'">'+U[v[1]]+'</b></div></td>').join('')+'</tr>'});
const t=document.getElementById('s');t.innerHTML=h;const sd=document.getElementById('sd');
t.querySelectorAll('.k').forEach(e=>{const f=()=>{const r=S[e.dataset.i];sd.textContent=r[0]+' in '+C[e.dataset.j]+': '+r[1][e.dataset.j][2]};e.onclick=f;e.onkeydown=x=>{if(x.key==='Enter')f()}});
</script>
`;
if(process.argv.includes('--check')) {
    if(readFileSync(OUT, 'utf8') !== html) {console.error(`${OUT} is stale; run node scripts/cross_world_coverage.mjs`); process.exit(1);}
} else {writeFileSync(OUT, html); console.log(`${OUT}: ${data.length} systems × ${cols.length} worlds`);}
