// Rebuilt browser proof using only fresh contexts and explicitly generated saves.
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const {launchChrome,waitForPage}=require('./ui_helpers.cjs');
const {openNotebook} = require('./ui_helpers.cjs');
const url = process.env.YAIRPG_PROOF_URL || 'http://127.0.0.1:18549/';
const output = process.env.YAIRPG_PROOF_DIR || '/tmp/yairpg-people-proof'; fs.mkdirSync(output, {recursive:true});
(async () => {
    const browser = await launchChrome();try{
    const errors = [], findings = [];
    const open = async fixture => {
        const context = await browser.newContext({viewport:{width:1600,height:1100}});
        if(fixture) await context.addInitScript(data => {if(!localStorage.getItem('save data')) localStorage.setItem('save data', JSON.stringify(data));}, fixture);
        const page = await context.newPage(); page.setDefaultTimeout(12000); page.on('pageerror', e => errors.push(e.stack));
        await page.goto(url); await page.getByText('PLAY', {exact:true}).click();
        if(await page.getByText('Confirm', {exact:true}).isVisible()) await page.getByText('Confirm', {exact:true}).click();
        return {page, context};
    };
    const save = async page => {await page.evaluate(() => window.saveProgress()); return page.evaluate(() => JSON.parse(localStorage.getItem('save data')));};
    const people = async page => {await openNotebook(page); await page.locator('[data-notebook-view="people"]').click();};
    const travel = async (page, id) => {await page.getByText('Move somewhere else', {exact:false}).click(); await page.locator(`[data-travel="${id}"]`).click();};
    let {page, context} = await open();
    const fingerprint = await page.evaluate(() => performance.getEntriesByType('resource').find(e => e.name.includes('/dist/bundle.js?version='))?.name);
    assert.ok(fingerprint.endsWith(fs.readFileSync(process.env.YAIRPG_BUILD_INDEX || 'index.html', 'utf8').match(/dist\/bundle\.js\?version=[^&"]+/)[0]));
    assert.equal(await page.locator('#journal_show_notebook').isVisible(), false);
    assert.equal(await page.locator('[data-known-person]').count(), 0);
    await page.getByRole('button',{name:'Talk to someone'}).click(); await page.locator('[data-dialogue="villageElder"]').click();
    await page.locator('[data-textline="hello"]').click();
    await people(page); assert.equal(await page.locator('[data-known-person="villageElder"]').isVisible(), true);
    assert.equal(await page.locator('#chronicle_panel').isVisible(), false);
    assert.equal(await page.locator('[data-notebook-view="here"]').isVisible(), false);
    assert.equal(await page.locator('[data-notebook-view="practice"]').isVisible(), false);
    await page.locator('.end_dialogue_button').click(); await people(page);
    assert.equal(await page.locator('#simulation_panel').isVisible(), false);
    const elder = page.locator('[data-known-person="villageElder"]'); await elder.locator('summary').click();
    assert.equal(await page.locator('[data-known-person]').count(), 1);
    assert.doesNotMatch(await elder.textContent(), /strength|control|trust|archive|successor/i);
    await elder.locator('summary').focus(); await page.waitForTimeout(1100);
    assert.equal(await elder.evaluate(n => n.open), true);
    assert.equal(await page.evaluate(() => document.activeElement.parentElement.dataset.knownPerson), 'villageElder');
    const base = await save(page); assert.equal(base.expansion.simulation, null); assert.equal(base.expansion.chronicle, null);
    findings.push('A fresh opening has no record or Notebook. The actual greeting introduces only the elder. Records are readable during dialogue while actions/empty tabs stay hidden; expansion and focus survive ticks.');
    await context.close();

    const traveling = structuredClone(base); traveling.availabilities.location['Forest road'] |= 1;
    ({page, context} = await open(traveling)); await people(page); await travel(page, 'Forest road');
    assert.equal(await page.locator('[data-notebook-view="people"]').getAttribute('aria-selected'), 'true');
    assert.equal(await page.locator('[data-known-person="villageElder"]').isVisible(), true);
    assert.equal(await page.locator('#chronicle_panel').isVisible(), false);
    const before = await save(page); await page.reload(); await page.getByText('PLAY', {exact:true}).click(); await people(page);
    const after = await save(page); assert.deepEqual(after.expansion.actors, before.expansion.actors);
    assert.deepEqual(after.inventories, before.inventories); assert.equal(after.character.money, before.character.money);
    assert.equal(after.expansion.simulation, null); assert.equal(after.expansion.chronicle, null);
    assert.match(await page.locator('[data-known-person="villageElder"]').textContent(), /Last known: Village/);
    findings.push('Native travel retains the selected People view and learned record away from Village. Reload retains its native greeting marker without granting rewards, moving NPCs or enrolling life/work. Travel access is generated for this bounded proof.');
    await context.close();

    const ready = structuredClone(base), wood = JSON.stringify({id:'Rough wood log'});
    ready.character.money = 30; ready.inventories.person.main_character[wood] = {count:10};
    ready.availabilities.textline['oldCraftsman:hello'] |= 4;
    ({page, context} = await open(ready)); await people(page);
    const craftsman = page.locator('[data-known-person="oldCraftsman"]'); await craftsman.locator('summary').click();
    assert.doesNotMatch(await craftsman.textContent(), /quiet|fittings|trust|commission/i);
    await page.locator('#simulation_panel > summary').click(); await page.locator('[data-simulation="enroll"]').click();
    assert.doesNotMatch(await craftsman.textContent(), /quiet|fittings|trust|commission/i);
    await page.locator('[data-simulation="village.working_habits"]').click();
    assert.match(await craftsman.textContent(), /quiet while counting fittings/);
    await page.locator('[data-simulation="village.commission"]').click();
    assert.match(await craftsman.textContent(), /supplied the agreed wood/);
    assert.doesNotMatch(await page.locator('#simulation_panel').textContent(), /Craftsman's trust:/);
    const commissioned = await save(page); await page.reload(); await page.getByText('PLAY', {exact:true}).click(); await people(page);
    assert.match(await craftsman.textContent(), /quiet while counting fittings|supplied the agreed wood/);
    const reloaded = await save(page); assert.equal(reloaded.expansion.simulation.relationships.oldCraftsman.player.axes.trust, commissioned.expansion.simulation.relationships.oldCraftsman.player.axes.trust);
    await page.locator('[data-known-person="villageElder"] summary').click(); await craftsman.locator('summary').click();
    await page.screenshot({path:path.join(output, 'known-people.png'), fullPage:true});
    fs.writeFileSync(path.join(output, 'generated-people-review.json'), JSON.stringify(reloaded, null, 2));
    findings.push('Generated native craftsman access reveals only his name/place. Enrollment adds no preferences. Actual questions and a real paid/material commission add their own evidence, survive reload, and leave the hidden relationship axis intact.');
    await context.close();

    const gate = structuredClone(base); gate['current location'] = 'Town outskirts'; gate.availabilities.location['Town outskirts'] |= 1;
    ({page, context} = await open(gate)); await openNotebook(page);
    if(!await page.locator('#town_panel').evaluate(n => n.open)) await page.locator('#town_panel > summary').click();
    await page.locator('[data-town-action="town.begin"]').click();
    assert.equal(await page.locator('[data-known-person="town.surveyClerk"]').count(), 0);
    await travel(page, 'Town square'); await openNotebook(page);
    if(!await page.locator('#town_panel').evaluate(n => n.open)) await page.locator('#town_panel > summary').click();
    await page.locator('[data-town-action="town.brief"]').click();
    await people(page); const clerk = page.locator('[data-known-person="town.surveyClerk"]'); assert.equal(await clerk.isVisible(), true);
    assert.match(await clerk.textContent(), /agreed to provide/); assert.doesNotMatch(await clerk.textContent(), /paid|ledger|accepted/);
    findings.push('The optional permit does not introduce the clerk. The actual office briefing does, revealing the agreed work without settlement or later-ledger spoilers.');
    const result = {url, fingerprint, findings, errors, generatedSavesOnly:true};
    fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify(result, null, 2)); console.log(JSON.stringify(result, null, 2));
    assert.deepEqual(errors, []); }finally{await browser.close().catch(()=>{});}
})().catch(e => {console.error(e); process.exit(1);});
