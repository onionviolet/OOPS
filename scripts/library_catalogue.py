#!/usr/bin/env python3 -I
"""Regenerates docs/research/CALIBRE_CATALOGUE.md and SOURCE_LIBRARY_CATALOGUE.md (titles, authors, formats only) from the two local book databases,
opened read-only. Run after books are added: python3 -I scripts/library_catalogue.py"""
import sqlite3, json, os, pathlib

HOME = pathlib.Path.home()
OUT = pathlib.Path(__file__).resolve().parent.parent / 'docs' / 'research'
cell = lambda x: str(x or '').replace('|', '/').replace('\n', ' ').strip()


def ro(path):
    return sqlite3.connect(f'file:{path}?mode=ro', uri=True)


def calibre():
    c = ro(HOME / 'Calibre Library' / 'metadata.db')
    rows = c.execute("""select b.id, b.title,
        coalesce((select group_concat(a.name,'; ') from books_authors_link l join authors a on a.id=l.author where l.book=b.id),''),
        coalesce((select group_concat(lower(format),',') from data d where d.book=b.id),'') from books b order by b.id""").fetchall()
    lines = ['# Calibre catalogue (every book in the local library)', '',
             f'Generated by `scripts/library_catalogue.py` from `~/Calibre Library/metadata.db`, read-only: {len(rows)} books. Titles, authors and formats only. '
             'Path pattern: `~/Calibre Library/<author folder>/<title> (<id>)/`. Author folders are unreliable (one series can sit under several spellings), so search by ID or title here. '
             'Prime reading books are in [LIBRARY_INDEX](LIBRARY_INDEX.md); the other store is [SOURCE_LIBRARY_CATALOGUE](SOURCE_LIBRARY_CATALOGUE.md).', '',
             '| ID | Title | Author | Formats |', '|---|---|---|---|']
    lines += [f'| {r[0]} | {cell(r[1])} | {cell(r[2])} | {cell(r[3])} |' for r in rows]
    (OUT / 'CALIBRE_CATALOGUE.md').write_text('\n'.join(lines) + '\n', encoding='utf8')
    return len(rows)


def source_library():
    c = ro(HOME / '.local/share/source-platform/catalogue.sqlite')
    rows = []
    for h, m in c.execute('select hash, metadata from assets'):
        m = json.loads(m)
        rows.append((cell(m.get('title')), cell(m.get('author')), cell(m.get('kind')), cell(m.get('language')), h[:10]))
    rows.sort(key=lambda r: r[0].lower())
    lines = ['# Source Library catalogue (the second book store)', '',
             f'Generated by `scripts/library_catalogue.py` from `~/.local/share/source-platform/catalogue.sqlite`, read-only: {len(rows)} assets. Titles, authors and kinds only. '
             'Files live at `~/.local/share/source-platform/library/<sha256>/` (the short hash below is its first 10 characters). Many books here were also imported into Calibre; '
             'the same title can appear in both, and some titles repeat here under several editions. Mostly tabletop rulebooks and light novels. Use the Source Library CLI or MCP to search and download; see [source acquisition tools](SOURCE_ACQUISITION_TOOLS.md). '
             'Prime books: [LIBRARY_INDEX](LIBRARY_INDEX.md).', '',
             '| Title | Author | Kind | Lang | Hash |', '|---|---|---|---|---|']
    lines += [f'| {" | ".join(r)} |' for r in rows]
    (OUT / 'SOURCE_LIBRARY_CATALOGUE.md').write_text('\n'.join(lines) + '\n', encoding='utf8')
    return len(rows)


if __name__ == '__main__':
    print('calibre', calibre(), 'source-library', source_library())
