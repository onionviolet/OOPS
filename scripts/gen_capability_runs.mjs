#!/usr/bin/env node
// Self-registration for capability runs (merge friction, 2026-11-18). A lane adds src/capability_runs/<id>.js
//   export default {id, order, run, world?};   // world: the book prefix whose lead sees the run (G6)
// and nothing else. This writes the barrel src/capability_runs/index.js from the folder. The merge queue and build.js
// rerun it, so two lanes adding runs never conflict on the barrel.
//   node scripts/gen_capability_runs.mjs          write the barrel
//   node scripts/gen_capability_runs.mjs --check  exit 1 when it is stale
import {readdirSync, readFileSync, writeFileSync, existsSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';

const dir = join(fileURLToPath(new URL('..', import.meta.url)), 'src/capability_runs');
export function barrel() {
    const names = readdirSync(dir).filter(f => f.endsWith('.js') && f !== 'index.js').sort().map(f => f.replace(/\.js$/, ''));
    return `// Generated by scripts/gen_capability_runs.mjs from this folder; do not edit.\n${names.map((n, i) => `import d${i} from './${n}.js';`).join('\n')}\nexport const CAPABILITY_RUNS = [${names.map((_, i) => `d${i}`).join(', ')}];\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const out = barrel(), file = join(dir, 'index.js');
    if (process.argv.includes('--check')) process.exit(existsSync(file) && readFileSync(file, 'utf8') === out ? 0 : 1);
    writeFileSync(file, out);
}
