// Writes the simfuzz coverage report: REPORT.md (summary, invariant failures
// with reproductions, perf notes), COMMANDS.md (every registered command with
// its reach status) and results.json (machine-readable summary).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execSync} from 'node:child_process';
import * as H from './harness.mjs';

const esc = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const sh = c => { try { return execSync(c, {cwd: H.ROOT, encoding: 'utf8'}).trim(); } catch { return '?'; } };

// Normalize a failure message so the same defect from many seeds groups together.
const signature = f => `${f.kind}: ${String(f.detail).replace(/\d+/g, '#').replace(/"[^"]*"/g, '"…"').slice(0, 160)}`;

export async function writeReport({results, seeds, steps, workers, wall, from = 0, dir, loadStart = null, jsonl = null}) {
    const E = await H.loadEngine();
    const catalog = H.buildCatalog(E);
    fs.mkdirSync(dir, {recursive: true});
    const main = results.filter(r => !r.rerun && !r.harnessError);
    const reruns = results.filter(r => r.rerun && !r.harnessError);
    const union = k => new Set(main.flatMap(r => r[k] || []));
    const eligible = union('eligible'), committed = union('committed'), attempted = union('attempted');
    const initial = {};
    for (const r of main) if (r.initialEligible?.length) (initial[r.fixture] ||= new Set()) && r.initialEligible.forEach(k => initial[r.fixture].add(k));
    const rejected = {}, previewThrew = {};
    for (const r of main) {
        for (const [k, v] of Object.entries(r.rejected || {})) rejected[k] ||= v;
        for (const [k, v] of Object.entries(r.previewThrew || {})) previewThrew[k] ||= v;
    }
    const status = row => committed.has(row.key) ? 'committed'
        : eligible.has(row.key) ? 'eligible, never committed'
        : attempted.has(row.key) ? 'attempted, rejected'
        : previewThrew[row.key] ? 'preview threw'
        : 'never eligible';

    // Failures: group by signature, keep the occurrence with the smallest step.
    const groups = new Map();
    for (const r of main) for (const f of r.failures || []) {
        const sig = signature(f);
        const g = groups.get(sig) || {sig, kind: f.kind, count: 0, seeds: new Set(), best: f};
        g.count++; g.seeds.add(f.seed);
        if (f.step < g.best.step || (f.step === g.best.step && f.seed < g.best.seed)) g.best = f;
        groups.set(sig, g);
    }
    const determinism = reruns.map(rr => {
        const m = main.find(r => r.seed === rr.seed);
        return {seed: rr.seed, policy: rr.policy, fixture: rr.fixture, first: m?.finalHash, second: rr.finalHash, equal: m?.finalHash === rr.finalHash};
    });
    for (const d of determinism) if (!d.equal) groups.set('determinism:' + d.seed, {sig: 'determinism', kind: 'determinism', count: 1, seeds: new Set([d.seed]),
        best: {seed: d.seed, step: steps, kind: 'determinism', action: 'whole run', detail: `same seed gave final hash ${d.first} then ${d.second}`}});

    const timing = {};
    for (const r of main) for (const [k, v] of Object.entries(r.timing || {})) timing[k] = (timing[k] || 0) + v;
    const totalStepMs = main.reduce((a, r) => a + r.ms, 0);
    const policies = {};
    for (const r of main) {
        const p = policies[r.policy] ||= {seeds: 0, steps: 0, commits: 0, advances: 0, minutes: 0, roundTrips: 0, splitChecks: 0, advTried: 0, advRejected: 0, failures: 0};
        p.seeds++; p.steps += r.steps; p.commits += r.commits; p.advances += r.advances; p.minutes += r.minutes;
        p.roundTrips += r.roundTrips; p.splitChecks += r.splitChecks; p.advTried += r.adversarial.tried; p.advRejected += r.adversarial.rejected; p.failures += r.failures.length;
    }
    const byGroup = {};
    for (const row of catalog) {
        const g = byGroup[row.group] ||= {total: 0, eligible: 0, committed: 0, route: row.route};
        g.total++; if (eligible.has(row.key) || committed.has(row.key)) g.eligible++; if (committed.has(row.key)) g.committed++;
    }
    const guarded = {};
    for (const r of main) for (const [k, v] of Object.entries(r.guarded || {})) {
        const why = (r.rejected?.[k] || '').match(/publication guard (\w+)/)?.[1] || '?';
        guarded[why] = (guarded[why] || 0) + v;
    }
    const layerErrors = {};
    for (const r of main) for (const [k, v] of Object.entries(r.layerErrors || {})) layerErrors[k] = (layerErrors[k] || 0) + v;

    const head = sh('git rev-parse --short HEAD'), branch = sh('git rev-parse --abbrev-ref HEAD');
    const load = os.loadavg().map(x => x.toFixed(0)).join(' / ');
    const L = [];
    L.push('# Engine simulation fuzzer report', '');
    L.push(`Generated by \`node scripts/simfuzz/run.mjs --seeds ${seeds} --steps ${steps}\` on ${branch} @ ${head}, ${new Date().toISOString().slice(0, 16)}Z.`);
    L.push(`Node ${process.version}, ${workers} worker processes, ${os.availableParallelism()} cores. Load average at start ${loadStart ?? '?'}, at end ${load} (1/5/15 min).`);
    L.push(`${main.length} seeds plus ${reruns.length} determinism reruns (${main.reduce((a, r) => a + r.steps, 0)} main steps). Last invocation wall time ${(wall / 1000).toFixed(1)} s${jsonl ? `; per-seed results in \`${jsonl}\` (a resumed run spans several invocations)` : ''}.`, '');
    // CPU-seconds per seed is the load-independent cost; wall time depends on the host.
    const all = [...main, ...reruns], cpu = all.reduce((a, r) => a + (r.cpuSeconds || 0), 0);
    const byFixture = {};
    for (const r of all) (byFixture[r.fixture] ||= []).push(r.cpuSeconds || 0);
    const med = a => { const b = [...a].sort((x, y) => x - y); return b.length ? b[b.length >> 1] : 0; };
    L.push('### Cost', '');
    L.push(`Total ${cpu.toFixed(0)} CPU-seconds. Projected wall time for the whole run on an idle host with W free cores is about total / W: ${(cpu / 4 / 60).toFixed(1)} min at 4, ${(cpu / 16 / 60).toFixed(1)} min at 16.`, '');
    L.push('| Fixture | Runs | Median CPU-s per seed | Max | Median ms CPU per step |', '| --- | --- | --- | --- | --- |');
    for (const [fx, a] of Object.entries(byFixture)) L.push(`| ${fx} | ${a.length} | ${med(a).toFixed(1)} | ${Math.max(...a).toFixed(1)} | ${(1000 * med(a) / steps).toFixed(1)} |`);
    L.push('');
    L.push('Method, policies and invariants: [scripts/simfuzz/README.md](../../../../../scripts/simfuzz/README.md). Every registered command and its reach status: [COMMANDS.md](COMMANDS.md).', '');
    L.push('## Summary', '');
    L.push(`- Catalog: ${catalog.length} rows (${Object.entries(catalog.reduce((a, r) => (a[r.kind] = (a[r.kind] || 0) + 1, a), {})).map(([k, v]) => `${v} ${k}`).join(', ')}).`);
    L.push(`- Ever eligible: ${[...new Set([...eligible, ...committed])].length}. Committed at least once: ${committed.size}. Never eligible: ${catalog.filter(r => status(r) === 'never eligible').length}.`);
    for (const [fx, set] of Object.entries(initial)) L.push(`- Eligible at the start of fixture \`${fx}\` (full sweep, step 1): ${set.size}.`);
    L.push(`- Invariant failure groups: ${groups.size}. Determinism reruns: ${determinism.filter(d => d.equal).length}/${determinism.length} identical.`);
    if (Object.keys(guarded).length) L.push(`- Plans refused by main.js publication guards (counted as host rejections, not failures): ${Object.entries(guarded).map(([k, v]) => `${k} x${v}`).join(', ')}.`);
    if (E.loadErrors.length) L.push(`- Harness import gaps: ${E.loadErrors.join('; ')}.`);
    if (Object.keys(layerErrors).length) L.push(`- Context layers that threw on the synthetic context (skipped, harness gap): ${Object.entries(layerErrors).map(([k, v]) => `${k} x${v}`).join(', ')}.`);
    L.push('');
    L.push('| Policy | Seeds | Steps | Commits | Advances | Game minutes | Round-trips | Split checks | Adversarial tried / rejected | Failures |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
    for (const [k, p] of Object.entries(policies)) L.push(`| ${k} | ${p.seeds} | ${p.steps} | ${p.commits} | ${p.advances} | ${p.minutes} | ${p.roundTrips} | ${p.splitChecks} | ${p.advTried} / ${p.advRejected} | ${p.failures} |`);
    L.push('', '## Invariant failures', '');
    if (!groups.size) L.push('None.');
    else {
        L.push('Each row is one defect signature. Reproduce with `node scripts/simfuzz/run.mjs --repro <seed> --stop-at <step>` (prints the action trace and failures up to that step). The seed fixes policy and fixture.', '');
        L.push('| Kind | Occurrences | Seeds | Minimal repro (seed, step) | Policy / fixture | Action | Detail |', '| --- | --- | --- | --- | --- | --- | --- |');
        for (const g of [...groups.values()].sort((a, b) => b.count - a.count)) {
            const f = g.best;
            L.push(`| ${g.kind} | ${g.count} | ${g.seeds.size} | \`--repro ${f.seed} --stop-at ${f.step}\` | ${H.policyForSeed(f.seed)} / ${H.fixtureForSeed(f.seed)} | ${esc(f.action)} | ${esc(f.detail)} |`);
        }
    }
    L.push('', '## Determinism', '');
    L.push('| Seed | Policy / fixture | First hash | Rerun hash | Equal |', '| --- | --- | --- | --- | --- |');
    for (const d of determinism) L.push(`| ${d.seed} | ${d.policy} / ${d.fixture} | ${d.first} | ${d.second} | ${d.equal ? 'yes' : '**no**'} |`);
    L.push('', '## Coverage by group', '');
    L.push('| Group | Route | Rows | Ever eligible | Committed |', '| --- | --- | --- | --- | --- |');
    for (const [g, v] of Object.entries(byGroup).sort((a, b) => a[0].localeCompare(b[0]))) L.push(`| ${g} | ${v.route} | ${v.total} | ${v.eligible} | ${v.committed} |`);
    L.push('', '## Where the time went', '');
    L.push(`Summed over main seeds (${(totalStepMs / 1000).toFixed(0)} s of worker time):`, '');
    L.push('| Phase | Seconds | Share |', '| --- | --- | --- |');
    const tsum = Object.values(timing).reduce((a, b) => a + b, 0) || 1;
    for (const [k, v] of Object.entries(timing).sort((a, b) => b[1] - a[1])) L.push(`| ${k} | ${(v / 1000).toFixed(1)} | ${(100 * v / tsum).toFixed(0)}% |`);
    L.push('');
    fs.writeFileSync(path.join(dir, 'REPORT.md'), L.join('\n') + '\n');

    const C = ['# Simfuzz command reach status', '',
        `Every registered command row from \`buildCatalog\` (${catalog.length}), from the run in [REPORT.md](REPORT.md).`,
        'Status: **committed** = a policy committed it; **eligible, never committed** = a preview said eligible but no commit landed;',
        '**attempted, rejected** = sampled and committed but the engine or host refused (first reason shown); **preview threw** = the preview itself threw;',
        '**never eligible** = never passed a preview from these fixtures. Start columns: eligible in the full sweep at step 1 of that fixture.', '',
        '| Command | Kind | Group | Route | Status | fresh | mid | crowded | First rejection or preview error |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- |'];
    for (const row of catalog) C.push(`| \`${row.key}\` | ${row.kind} | ${row.group} | ${row.route} | ${status(row)} | ${initial.fresh?.has(row.key) ? 'y' : ''} | ${initial.mid?.has(row.key) ? 'y' : ''} | ${initial.crowded?.has(row.key) ? 'y' : ''} | ${esc((rejected[row.key] || previewThrew[row.key] || '').slice(0, 140))} |`);
    fs.writeFileSync(path.join(dir, 'COMMANDS.md'), C.join('\n') + '\n');

    const json = {generated: new Date().toISOString(), head, seeds, steps, workers, wallMs: wall, loadStart, loadEnd: load,
        statusCounts: catalog.reduce((a, r) => (a[status(r)] = (a[status(r)] || 0) + 1, a), {}),
        commands: Object.fromEntries(catalog.map(r => [r.key, status(r)])),
        failures: [...groups.values()].map(g => ({kind: g.kind, signature: g.sig, count: g.count, seeds: [...g.seeds], repro: {seed: g.best.seed, step: g.best.step}, action: g.best.action, detail: g.best.detail})),
        determinism, policies, timing, guarded, layerErrors, loadErrors: E.loadErrors};
    fs.writeFileSync(path.join(dir, 'results.json'), JSON.stringify(json, null, 1) + '\n');
    return ['REPORT.md', 'COMMANDS.md', 'results.json'].map(f => path.join(dir, f));
}
